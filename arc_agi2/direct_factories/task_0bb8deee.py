def build_program(d4, palette):
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('')
    lines.append('def _divider_rows(g):')
    lines.append('    out = []')
    lines.append('    for y in range(g.shape[0]):')
    lines.append('        v = g[y, 0]')
    lines.append('        if v != BG and (g[y] == v).all():')
    lines.append('            out.append(y)')
    lines.append('    return out')
    lines.append('')
    lines.append('def _divider_cols(g):')
    lines.append('    out = []')
    lines.append('    for x in range(g.shape[1]):')
    lines.append('        v = g[0, x]')
    lines.append('        if v != BG and (g[:, x] == v).all():')
    lines.append('            out.append(x)')
    lines.append('    return out')
    lines.append('')
    lines.append('def _spans(cuts, n):')
    lines.append('    edges = [-1] + sorted(cuts) + [n]')
    lines.append('    res = []')
    lines.append('    for a, b in zip(edges[:-1], edges[1:]):')
    lines.append('        if b - a > 1:')
    lines.append('            res.append((a + 1, b - 1))')
    lines.append('    return res')
    lines.append('')
    lines.append('def _crop(sub):')
    lines.append('    ys, xs = np.where(sub != BG)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return None')
    lines.append('    return sub[ys.min():ys.max() + 1, xs.min():xs.max() + 1]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    rows = _divider_rows(g)')
    lines.append('    cols = _divider_cols(g)')
    lines.append('    ys = _spans(rows, H)')
    lines.append('    xs = _spans(cols, W)')
    lines.append('    nr, nc = len(ys), len(xs)')
    lines.append('    out = np.full((3 * nr, 3 * nc), BG, dtype=int)')
    lines.append('    for r, (y0, y1) in enumerate(ys):')
    lines.append('        for c, (x0, x1) in enumerate(xs):')
    lines.append('            cr = _crop(g[y0:y1 + 1, x0:x1 + 1])')
    lines.append('            if cr is None:')
    lines.append('                continue')
    lines.append('            cr = cr[:3, :3]')
    lines.append('            h, w = cr.shape')
    lines.append('            out[3 * r:3 * r + h, 3 * c:3 * c + w] = cr')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
