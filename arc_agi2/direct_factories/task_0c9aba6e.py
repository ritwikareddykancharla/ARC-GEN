def build_program(d4, palette):
    k = int(d4) % 4
    # Original divider is a horizontal row of colour 7. An odd number of clockwise
    # rotations turns it into a vertical column. A reflection does not change the axis.
    axis = 'cols' if k in (1, 3) else 'rows'
    div = int(palette[7])
    bg = int(palette[0])
    fill = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('AXIS = %r' % axis)
    lines.append('DIV = %d' % div)
    lines.append('BG = %d' % bg)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def _find_row(g):')
    lines.append('    h = g.shape[0]')
    lines.append('    cands = [y for y in range(h) if (g[y, :] == DIV).all()]')
    lines.append('    for y in cands:')
    lines.append('        if int(np.sum(g == DIV)) == g.shape[1]:')
    lines.append('            return y')
    lines.append('    if cands:')
    lines.append('        mid = h // 2')
    lines.append('        return min(cands, key=lambda y: abs(y - mid))')
    lines.append('    return h // 2')
    lines.append('')
    lines.append('def _find_col(g):')
    lines.append('    w = g.shape[1]')
    lines.append('    cands = [x for x in range(w) if (g[:, x] == DIV).all()]')
    lines.append('    for x in cands:')
    lines.append('        if int(np.sum(g == DIV)) == g.shape[0]:')
    lines.append('            return x')
    lines.append('    if cands:')
    lines.append('        mid = w // 2')
    lines.append('        return min(cands, key=lambda x: abs(x - mid))')
    lines.append('    return w // 2')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    if AXIS == "rows":')
    lines.append('        d = _find_row(g)')
    lines.append('        a = g[:d, :]')
    lines.append('        b = g[d + 1:, :]')
    lines.append('        n = min(a.shape[0], b.shape[0])')
    lines.append('        a = a[:n, :]')
    lines.append('        b = b[:n, :]')
    lines.append('    else:')
    lines.append('        d = _find_col(g)')
    lines.append('        a = g[:, :d]')
    lines.append('        b = g[:, d + 1:]')
    lines.append('        n = min(a.shape[1], b.shape[1])')
    lines.append('        a = a[:, :n]')
    lines.append('        b = b[:, :n]')
    lines.append('    out = np.full(a.shape, BG, dtype=int)')
    lines.append('    out[(a == BG) & (b == BG)] = FILL')
    lines.append('    return [[int(v) for v in row] for row in out.tolist()]')
    return '\n'.join(lines) + '\n'
