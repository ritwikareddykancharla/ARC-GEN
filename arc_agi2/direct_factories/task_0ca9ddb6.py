def build_program(d4, palette):
    bg = int(palette[0])
    rook_seed = int(palette[1])
    bishop_seed = int(palette[2])
    rook_colour = int(palette[7])
    bishop_colour = int(palette[4])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('ROOK_SEED = %d' % rook_seed)
    lines.append('BISHOP_SEED = %d' % bishop_seed)
    lines.append('ROOK_COLOUR = %d' % rook_colour)
    lines.append('BISHOP_COLOUR = %d' % bishop_colour)
    lines.append('# The plus (rook) and X (bishop) motifs are invariant under every D4 transform,')
    lines.append('# so the same offsets apply in visible coordinates; only colour roles change.')
    lines.append('ORTHO = [(-1, 0), (1, 0), (0, -1), (0, 1)]')
    lines.append('DIAG = [(-1, -1), (-1, 1), (1, -1), (1, 1)]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    H, W = g.shape')
    lines.append('    legend = {ROOK_SEED: (ROOK_COLOUR, ORTHO), BISHOP_SEED: (BISHOP_COLOUR, DIAG)}')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            v = int(g[y, x])')
    lines.append('            if v == BG or v not in legend:')
    lines.append('                continue')
    lines.append('            colour, offs = legend[v]')
    lines.append('            for dy, dx in offs:')
    lines.append('                ny, nx = y + dy, x + dx')
    lines.append('                if 0 <= ny < H and 0 <= nx < W and out[ny, nx] == BG:')
    lines.append('                    out[ny, nx] = colour')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
