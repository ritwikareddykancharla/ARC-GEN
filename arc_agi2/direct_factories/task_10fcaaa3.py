def build_program(d4, palette):
    bg = int(palette[0])
    halo = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('HALO = %d' % halo)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = np.tile(g, (2, 2))')
    lines.append('    OH, OW = out.shape')
    lines.append('    coloured = out != BG')
    lines.append('    mark = np.zeros((OH, OW), dtype=bool)')
    lines.append('    ys, xs = np.nonzero(coloured)')
    lines.append('    for dy, dx in ((-1, -1), (-1, 1), (1, -1), (1, 1)):')
    lines.append('        ny = ys + dy')
    lines.append('        nx = xs + dx')
    lines.append('        ok = (ny >= 0) & (ny < OH) & (nx >= 0) & (nx < OW)')
    lines.append('        mark[ny[ok], nx[ok]] = True')
    lines.append('    out[mark & ~coloured] = HALO')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
