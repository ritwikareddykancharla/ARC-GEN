def build_program(d4, palette):
    bg = int(palette[0])
    tc = int(palette[1])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('TEMPLATE = %d' % tc)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    ys, xs = np.where(g == TEMPLATE)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return [[BG]]')
    lines.append('    y0, y1, x0, x1 = ys.min(), ys.max(), xs.min(), xs.max()')
    lines.append('    tmpl = g[y0:y1 + 1, x0:x1 + 1] == TEMPLATE')
    lines.append('    th, tw = tmpl.shape')
    lines.append('    marks = []')
    lines.append('    for y, x in zip(*np.where((g != BG) & (g != TEMPLATE))):')
    lines.append('        if y0 <= y <= y1 and x0 <= x <= x1:')
    lines.append('            continue')
    lines.append('        marks.append((int(y), int(x), int(g[y, x])))')
    lines.append('    if not marks:')
    lines.append('        return np.where(tmpl, TEMPLATE, BG).astype(int).tolist()')
    lines.append('    rows = set(m[0] for m in marks)')
    lines.append('    cols = set(m[1] for m in marks)')
    lines.append('    # Legend lies on one line; copies are laid out along the same axis,')
    lines.append('    # in the same spatial order as the legend markers.')
    lines.append('    if len(rows) == 1 and len(cols) > 1:')
    lines.append('        horizontal = True')
    lines.append('    elif len(cols) == 1 and len(rows) > 1:')
    lines.append('        horizontal = False')
    lines.append('    else:')
    lines.append('        horizontal = (max(cols) - min(cols)) >= (max(rows) - min(rows))')
    lines.append('    if horizontal:')
    lines.append('        marks.sort(key=lambda m: (m[1], m[0]))')
    lines.append('    else:')
    lines.append('        marks.sort(key=lambda m: (m[0], m[1]))')
    lines.append('    k = len(marks)')
    lines.append('    if horizontal:')
    lines.append('        out = np.full((th, tw * k), BG, dtype=int)')
    lines.append('    else:')
    lines.append('        out = np.full((th * k, tw), BG, dtype=int)')
    lines.append('    for i, (_, _, c) in enumerate(marks):')
    lines.append('        stamp = np.where(tmpl, c, BG)')
    lines.append('        if horizontal:')
    lines.append('            out[:, i * tw:(i + 1) * tw] = stamp')
    lines.append('        else:')
    lines.append('            out[i * th:(i + 1) * th, :] = stamp')
    lines.append('    return out.astype(int).tolist()')
    return '\n'.join(lines) + '\n'
