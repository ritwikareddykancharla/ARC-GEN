def build_program(d4, palette):
    gray = int(palette[5])
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('GRAY = %d' % gray)
    lines.append('BG = %d' % bg)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = np.full((3, 3), BG, dtype=int)')
    lines.append('    out[1, 1] = GRAY')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y, x] != GRAY:')
    lines.append('                continue')
    lines.append('            for dy in (-1, 0, 1):')
    lines.append('                for dx in (-1, 0, 1):')
    lines.append('                    yy = y + dy')
    lines.append('                    xx = x + dx')
    lines.append('                    if 0 <= yy < H and 0 <= xx < W:')
    lines.append('                        c = int(g[yy, xx])')
    lines.append('                        if c != BG and c != GRAY:')
    lines.append('                            out[dy + 1, dx + 1] = c')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
