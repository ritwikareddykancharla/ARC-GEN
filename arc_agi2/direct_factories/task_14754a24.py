def build_program(d4, palette):
    black = int(palette[0])
    grey = int(palette[5])
    yellow = int(palette[4])
    red = int(palette[2])
    lines = []
    lines.append('BLACK = %d' % black)
    lines.append('GREY = %d' % grey)
    lines.append('YELLOW = %d' % yellow)
    lines.append('RED = %d' % red)
    lines.append('')
    lines.append('def _plus(y, x):')
    lines.append('    return [(y, x), (y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)]')
    lines.append('')
    lines.append('def _components8(g, color, H, W):')
    lines.append('    seen = set()')
    lines.append('    comps = []')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y][x] != color or (y, x) in seen:')
    lines.append('                continue')
    lines.append('            seen.add((y, x))')
    lines.append('            stack = [(y, x)]')
    lines.append('            comp = []')
    lines.append('            while stack:')
    lines.append('                cy, cx = stack.pop()')
    lines.append('                comp.append((cy, cx))')
    lines.append('                for dy in (-1, 0, 1):')
    lines.append('                    for dx in (-1, 0, 1):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < H and 0 <= nx < W and g[ny][nx] == color and (ny, nx) not in seen:')
    lines.append('                            seen.add((ny, nx))')
    lines.append('                            stack.append((ny, nx))')
    lines.append('            comps.append(sorted(comp))')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [[int(v) for v in row] for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    for comp in _components8(g, YELLOW, H, W):')
    lines.append('        cs = set(comp)')
    lines.append('        cands = set()')
    lines.append('        for (cy, cx) in cs:')
    lines.append('            for (ey, ex) in _plus(cy, cx):')
    lines.append('                inside = [(y, x) for (y, x) in _plus(ey, ex) if 0 <= y < H and 0 <= x < W]')
    lines.append('                if not cs <= set(inside):')
    lines.append('                    continue')
    lines.append('                if any(g[y][x] == BLACK for (y, x) in inside):')
    lines.append('                    continue')
    lines.append('                cands.add((ey, ex))')
    lines.append('        for (ey, ex) in sorted(cands):')
    lines.append('            for (y, x) in _plus(ey, ex):')
    lines.append('                if 0 <= y < H and 0 <= x < W and g[y][x] == GREY:')
    lines.append('                    out[y][x] = RED')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
