def build_program(d4, palette):
    bg = int(palette[7])
    mark = int(palette[5])
    ink = int(palette[8])
    lines = []
    lines.append('BG = %d' % bg)
    lines.append('MARK = %d' % mark)
    lines.append('INK = %d' % ink)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    out = [list(r) for r in grid]')
    lines.append('    H = len(out)')
    lines.append('    W = len(out[0]) if H else 0')
    lines.append('    pts = [(r, c) for r in range(H) for c in range(W) if out[r][c] != BG]')
    lines.append('    if not pts:')
    lines.append('        return out')
    lines.append('    rs = [p[0] for p in pts]')
    lines.append('    cs = [p[1] for p in pts]')
    lines.append('    r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)')
    lines.append('    occ = set(pts)')
    lines.append('    corners = [(r0, c0), (r0, c1), (r1, c0), (r1, c1)]')
    lines.append('    empty = [p for p in corners if p not in occ]')
    lines.append('    if not empty:')
    lines.append('        return out')
    lines.append('    er, ec = empty[0]')
    lines.append('    orr = r1 if er == r0 else r0')
    lines.append('    oc = c1 if ec == c0 else c0')
    lines.append('    a = (orr, ec)')
    lines.append('    b = (er, oc)')
    lines.append('    def draw(p, q):')
    lines.append('        n = max(abs(q[0] - p[0]), abs(q[1] - p[1]))')
    lines.append('        dr = (q[0] - p[0]) // n if n else 0')
    lines.append('        dc = (q[1] - p[1]) // n if n else 0')
    lines.append('        for k in range(n + 1):')
    lines.append('            y = p[0] + k * dr')
    lines.append('            x = p[1] + k * dc')
    lines.append('            if 0 <= y < H and 0 <= x < W and out[y][x] == BG:')
    lines.append('                out[y][x] = INK')
    lines.append('    draw((er, ec), a)')
    lines.append('    draw((er, ec), b)')
    lines.append('    draw(a, b)')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
