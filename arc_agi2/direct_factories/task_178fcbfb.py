def build_program(d4, palette):
    swapped = ((d4 % 4) % 2) == 1
    red = int(palette[2])
    blue = int(palette[1])
    green = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('RED = %d' % red)
    lines.append('ACROSS_COLOURS = (%d, %d)' % (green, blue))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    if not swapped:
        lines.append('    # red pixels extend into full vertical lines (whole column), painted first')
        lines.append('    red_cols = sorted(set(np.nonzero(g == RED)[1].tolist()))')
        lines.append('    for x in red_cols:')
        lines.append('        out[:, x] = RED')
        lines.append('    # the other two pixel colours extend into full horizontal lines, painted on top')
        lines.append('    for colour in ACROSS_COLOURS:')
        lines.append('        rows = sorted(set(np.nonzero(g == colour)[0].tolist()))')
        lines.append('        for y in rows:')
        lines.append('            out[y, :] = colour')
    else:
        lines.append('    # red pixels extend into full horizontal lines (whole row), painted first')
        lines.append('    red_rows = sorted(set(np.nonzero(g == RED)[0].tolist()))')
        lines.append('    for y in red_rows:')
        lines.append('        out[y, :] = RED')
        lines.append('    # the other two pixel colours extend into full vertical lines, painted on top')
        lines.append('    for colour in ACROSS_COLOURS:')
        lines.append('        cols = sorted(set(np.nonzero(g == colour)[1].tolist()))')
        lines.append('        for x in cols:')
        lines.append('            out[:, x] = colour')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
