def build_program(d4, palette):
    bg = int(palette[2])
    ink = int(palette[4])
    hi = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('INK = %d' % ink)
    lines.append('HIGHLIGHT = %d' % hi)
    lines.append('ARMS = ((-1, 0), (1, 0), (0, -1), (0, 1))')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    if g.ndim != 2 or g.size == 0:')
    lines.append('        return [list(map(int, r)) for r in grid]')
    lines.append('    H, W = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    centres = []')
    lines.append('    for y in range(1, H - 1):')
    lines.append('        for x in range(1, W - 1):')
    lines.append('            if g[y, x] != INK:')
    lines.append('                continue')
    lines.append('            if all(g[y + dy, x + dx] == INK for dy, dx in ARMS):')
    lines.append('                centres.append((y, x))')
    lines.append('    for y, x in centres:')
    lines.append('        out[y, x] = HIGHLIGHT')
    lines.append('        for dy, dx in ARMS:')
    lines.append('            out[y + dy, x + dx] = HIGHLIGHT')
    lines.append('    return [[int(v) for v in row] for row in out.tolist()]')
    return '\n'.join(lines) + '\n'
