def build_program(d4, palette):
    d4 = int(d4) % 8
    bg = int(palette[0])
    on = int(palette[1])
    div = int(palette[2])
    fg = int(palette[7])
    # The original divider is a vertical column. A reflection keeps it vertical.
    # An odd number of clockwise quarter turns makes it a horizontal row.
    horizontal = (d4 % 4) % 2 == 1
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('ON = %d' % on)
    lines.append('DIV = %d' % div)
    lines.append('FG = %d' % fg)
    lines.append('HORIZONTAL = %s' % ('True' if horizontal else 'False'))
    lines.append('')
    lines.append('def _find_divider_col(g):')
    lines.append('    h, w = g.shape')
    lines.append('    cands = [x for x in range(w) if (g[:, x] == DIV).all()]')
    lines.append('    if cands:')
    lines.append('        mid = (w - 1) / 2.0')
    lines.append('        return min(cands, key=lambda x: abs(x - mid))')
    lines.append('    for x in range(w):')
    lines.append('        col = g[:, x]')
    lines.append('        if (col == col[0]).all() and (g == col[0]).sum() == h:')
    lines.append('            return x')
    lines.append('    return w // 2')
    lines.append('')
    lines.append('def _find_divider_row(g):')
    lines.append('    h, w = g.shape')
    lines.append('    cands = [y for y in range(h) if (g[y, :] == DIV).all()]')
    lines.append('    if cands:')
    lines.append('        mid = (h - 1) / 2.0')
    lines.append('        return min(cands, key=lambda y: abs(y - mid))')
    lines.append('    for y in range(h):')
    lines.append('        row = g[y, :]')
    lines.append('        if (row == row[0]).all() and (g == row[0]).sum() == w:')
    lines.append('            return y')
    lines.append('    return h // 2')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    if HORIZONTAL:')
    lines.append('        r = _find_divider_row(g)')
    lines.append('        a = g[:r, :]')
    lines.append('        b = g[r + 1:, :]')
    lines.append('        n = min(a.shape[0], b.shape[0])')
    lines.append('        a = a[:n, :]')
    lines.append('        b = b[:n, :]')
    lines.append('    else:')
    lines.append('        c = _find_divider_col(g)')
    lines.append('        a = g[:, :c]')
    lines.append('        b = g[:, c + 1:]')
    lines.append('        n = min(a.shape[1], b.shape[1])')
    lines.append('        a = a[:, :n]')
    lines.append('        b = b[:, :n]')
    lines.append('    out = np.full(a.shape, BG, dtype=int)')
    lines.append('    mask = (a != BG) | (b != BG)')
    lines.append('    out[mask] = ON')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
