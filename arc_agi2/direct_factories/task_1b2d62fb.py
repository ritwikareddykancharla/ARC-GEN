def build_program(d4, palette):
    d4 = int(d4) % 8
    rows_axis = (d4 % 4) in (1, 3)
    bg = int(palette[0])
    div = int(palette[1])
    mark = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DIV = %d' % div)
    lines.append('MARK = %d' % mark)
    lines.append('ROWS_AXIS = %s' % ('True' if rows_axis else 'False'))
    lines.append('')
    lines.append('def _pick(cands, n):')
    lines.append('    if not cands:')
    lines.append('        return n // 2')
    lines.append('    centre = (n - 1) / 2.0')
    lines.append('    return min(cands, key=lambda k: (abs(k - centre), k))')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    if ROWS_AXIS:')
    lines.append('        cands = [y for y in range(h) if (g[y, :] == DIV).all()]')
    lines.append('        y = _pick(cands, h)')
    lines.append('        a = g[:y, :]')
    lines.append('        b = g[y + 1:, :]')
    lines.append('        p = min(a.shape[0], b.shape[0])')
    lines.append('        a = a[:p, :]')
    lines.append('        b = b[:p, :]')
    lines.append('    else:')
    lines.append('        cands = [x for x in range(w) if (g[:, x] == DIV).all()]')
    lines.append('        x = _pick(cands, w)')
    lines.append('        a = g[:, :x]')
    lines.append('        b = g[:, x + 1:]')
    lines.append('        p = min(a.shape[1], b.shape[1])')
    lines.append('        a = a[:, :p]')
    lines.append('        b = b[:, :p]')
    lines.append('    out = np.where((a == BG) & (b == BG), MARK, BG)')
    lines.append('    return [[int(v) for v in row] for row in out.tolist()]')
    lines.append('')
    return '\n'.join(lines)
