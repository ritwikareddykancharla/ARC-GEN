def build_program(d4, palette):
    k = d4 % 4
    axis = 0 if k % 2 == 0 else 1
    rev = k in (1, 2)
    bg = int(palette[0])
    new = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('BG = %d' % bg)
    lines.append('NEW = %d' % new)
    lines.append('AXIS = %d' % axis)
    lines.append('REV = %s' % ('True' if rev else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    n = g.shape[AXIS]')
    lines.append('    order = list(range(n))')
    lines.append('    if REV:')
    lines.append('        order.reverse()')
    lines.append('    keys = []')
    lines.append('    for i in order:')
    lines.append('        vals = g[i, :] if AXIS == 0 else g[:, i]')
    lines.append('        nz = vals[vals != BG]')
    lines.append('        keys.append(int(nz[0]) if nz.size else BG)')
    lines.append('    out = g.copy()')
    lines.append('    bar = 0')
    lines.append('    j = 0')
    lines.append('    while j < n:')
    lines.append('        j1 = j')
    lines.append('        while j1 + 1 < n and keys[j1 + 1] == keys[j]:')
    lines.append('            j1 += 1')
    lines.append('        if bar % 3 == 0:')
    lines.append('            for t in range(j, j1 + 1):')
    lines.append('                i = order[t]')
    lines.append('                if AXIS == 0:')
    lines.append('                    seg = out[i, :]')
    lines.append('                else:')
    lines.append('                    seg = out[:, i]')
    lines.append('                seg[seg != BG] = NEW')
    lines.append('        bar += 1')
    lines.append('        j = j1 + 1')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
