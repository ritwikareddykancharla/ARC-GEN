def build_program(d4, palette):
    k = int(d4) % 4
    vertical = (k % 2 == 1)
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('VERTICAL = %s' % ('True' if vertical else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    h, w = out.shape')
    lines.append('    if VERTICAL:')
    lines.append('        # endpoints sit in the top and bottom rows; connect matching pairs down each column')
    lines.append('        for x in range(w):')
    lines.append('            a = int(g[0, x])')
    lines.append('            b = int(g[h - 1, x])')
    lines.append('            if a != BG and a == b:')
    lines.append('                out[:, x] = a')
    lines.append('    else:')
    lines.append('        # endpoints sit in the left and right columns; connect matching pairs across each row')
    lines.append('        for y in range(h):')
    lines.append('            a = int(g[y, 0])')
    lines.append('            b = int(g[y, w - 1])')
    lines.append('            if a != BG and a == b:')
    lines.append('                out[y, :] = a')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
