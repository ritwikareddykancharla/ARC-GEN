def build_program(d4, palette):
    bg = int(palette[0])
    marker = int(palette[8])
    fill = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('MARKER = %d' % marker)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    H, W = g.shape')
    lines.append('    pts = [(int(r), int(c)) for r, c in zip(*np.where(g == MARKER))]')
    lines.append('    n = len(pts)')
    lines.append('    for j in range(n):')
    lines.append('        for i in range(j):')
    lines.append('            ri, ci = pts[i]')
    lines.append('            rj, cj = pts[j]')
    lines.append('            if ri == rj:')
    lines.append('                lo, hi = min(ci, cj), max(ci, cj)')
    lines.append('                for c in range(lo + 1, hi):')
    lines.append('                    if g[ri, c] != MARKER:')
    lines.append('                        out[ri, c] = FILL')
    lines.append('            if ci == cj:')
    lines.append('                lo, hi = min(ri, rj), max(ri, rj)')
    lines.append('                for r in range(lo + 1, hi):')
    lines.append('                    if g[r, ci] != MARKER:')
    lines.append('                        out[r, ci] = FILL')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
