def build_program(d4, palette):
    d4 = int(d4) % 8
    by_columns = (d4 % 4) in (1, 3)
    uniform_colour = int(palette[5])
    mixed_colour = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BY_COLUMNS = %r' % (by_columns,))
    lines.append('UNIFORM_COLOUR = %d' % uniform_colour)
    lines.append('MIXED_COLOUR = %d' % mixed_colour)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    out = np.zeros((h, w), dtype=int)')
    lines.append('    if BY_COLUMNS:')
    lines.append('        for x in range(w):')
    lines.append('            col = g[:, x]')
    lines.append('            if np.all(col == col[0]):')
    lines.append('                out[:, x] = UNIFORM_COLOUR')
    lines.append('            else:')
    lines.append('                out[:, x] = MIXED_COLOUR')
    lines.append('    else:')
    lines.append('        for y in range(h):')
    lines.append('            row = g[y, :]')
    lines.append('            if np.all(row == row[0]):')
    lines.append('                out[y, :] = UNIFORM_COLOUR')
    lines.append('            else:')
    lines.append('                out[y, :] = MIXED_COLOUR')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
