def build_program(d4, palette):
    d4 = int(d4)
    transposed = (d4 % 4) % 2 == 1
    bg = int(palette[0])
    sep = int(palette[3])
    order = [int(palette[5]), int(palette[8]), int(palette[4]), int(palette[9])]
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('SEP = %d' % sep)
    lines.append('ORDER = %r' % (order,))
    lines.append('SEP_ROWS = %r' % (transposed,))
    lines.append('')
    lines.append('def _segments(g, rows):')
    lines.append('    n = g.shape[0] if rows else g.shape[1]')
    lines.append('    if rows:')
    lines.append('        seps = [i for i in range(n) if np.all(g[i, :] == SEP)]')
    lines.append('    else:')
    lines.append('        seps = [j for j in range(n) if np.all(g[:, j] == SEP)]')
    lines.append('    bounds = [-1] + seps + [n]')
    lines.append('    segs = []')
    lines.append('    for a, b in zip(bounds[:-1], bounds[1:]):')
    lines.append('        if b - a <= 1:')
    lines.append('            continue')
    lines.append('        segs.append(g[a + 1:b, :] if rows else g[:, a + 1:b])')
    lines.append('    return seps, segs')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    seps, segs = _segments(g, SEP_ROWS)')
    lines.append('    if not seps or not segs:')
    lines.append('        seps2, segs2 = _segments(g, not SEP_ROWS)')
    lines.append('        if seps2 and segs2:')
    lines.append('            seps, segs = seps2, segs2')
    lines.append('    if not segs:')
    lines.append('        return [list(map(int, r)) for r in g.tolist()]')
    lines.append('    shape = segs[0].shape')
    lines.append('    segs = [p for p in segs if p.shape == shape]')
    lines.append('    out = np.full(shape, BG, dtype=int)')
    lines.append('    for c in ORDER:')
    lines.append('        for p in segs:')
    lines.append('            out[p == c] = c')
    lines.append('    return [[int(v) for v in r] for r in out.tolist()]')
    return '\n'.join(lines) + '\n'
