def build_program(d4, palette):
    bg = int(palette[0])
    vertical = (int(d4) % 4) in (1, 3)
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('VERTICAL = %s' % ('True' if vertical else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    mask = g != BG')
    lines.append('    if not mask.any():')
    lines.append('        return g.tolist()')
    lines.append('    ys, xs = np.nonzero(mask)')
    lines.append('    y0, y1 = int(ys.min()), int(ys.max())')
    lines.append('    x0, x1 = int(xs.min()), int(xs.max())')
    lines.append('    motif = g[y0:y1 + 1, x0:x1 + 1].copy()')
    lines.append('    h, w = motif.shape')
    lines.append('    if VERTICAL:')
    lines.append('        out = np.full((2 * h, w), BG, dtype=int)')
    lines.append('        out[:h, :] = motif')
    lines.append('        out[h:, :] = motif')
    lines.append('    else:')
    lines.append('        out = np.full((h, 2 * w), BG, dtype=int)')
    lines.append('        out[:, :w] = motif')
    lines.append('        out[:, w:] = motif')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
