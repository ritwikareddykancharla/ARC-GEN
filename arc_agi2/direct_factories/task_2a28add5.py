def build_program(d4, palette):
    k = d4 % 4
    horizontal = (k % 2 == 0)
    bg = int(palette[7])
    anchor = int(palette[6])
    fill = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('ANCHOR = %d' % anchor)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = np.full_like(g, BG)')
    if horizontal:
        lines.append('    for y in range(H):')
        lines.append('        for x in range(W):')
        lines.append('            if g[y, x] != ANCHOR:')
        lines.append('                continue')
        lines.append('            before = int(np.sum(g[y, :x] != BG))')
        lines.append('            after = int(np.sum(g[y, x + 1:] != BG))')
        lines.append('            x0 = max(0, x - before)')
        lines.append('            x1 = min(W - 1, x + after)')
        lines.append('            out[y, x0:x1 + 1] = FILL')
    else:
        lines.append('    for x in range(W):')
        lines.append('        for y in range(H):')
        lines.append('            if g[y, x] != ANCHOR:')
        lines.append('                continue')
        lines.append('            before = int(np.sum(g[:y, x] != BG))')
        lines.append('            after = int(np.sum(g[y + 1:, x] != BG))')
        lines.append('            y0 = max(0, y - before)')
        lines.append('            y1 = min(H - 1, y + after)')
        lines.append('            out[y0:y1 + 1, x] = FILL')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
