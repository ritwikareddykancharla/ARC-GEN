def build_program(d4, palette):
    bg = int(palette[0])
    fill = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    if H < 3 or W < 3:')
    lines.append('        return out.tolist()')
    lines.append('    # visible rows: an interior row whose whole interior span is open background')
    lines.append('    for y in range(1, H - 1):')
    lines.append('        if np.all(g[y, 1:W - 1] == BG):')
    lines.append('            out[y, 1:W - 1] = FILL')
    lines.append('    # visible columns: tested on the ORIGINAL input, not on painted output')
    lines.append('    for x in range(1, W - 1):')
    lines.append('        if np.all(g[1:H - 1, x] == BG):')
    lines.append('            out[1:H - 1, x] = FILL')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
