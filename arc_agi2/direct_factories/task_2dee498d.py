def build_program(d4, palette):
    vertical = (d4 % 4) in (1, 3)
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('')
    lines.append('VERTICAL = %r' % vertical)
    lines.append('')
    lines.append('def _background(g):')
    lines.append('    return int(Counter(g.ravel().tolist()).most_common(1)[0][0])')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    vertical = VERTICAL')
    lines.append('    # The strip is three tiles along its long axis.')
    lines.append('    if vertical and w > h:')
    lines.append('        vertical = False')
    lines.append('    elif (not vertical) and h > w:')
    lines.append('        vertical = True')
    lines.append('    bg = _background(g)')
    lines.append('    if vertical:')
    lines.append('        th = h // 3')
    lines.append('        canvas = np.full((th, w), bg, dtype=int)')
    lines.append('        canvas[:, :] = g[:th, :]')
    lines.append('    else:')
    lines.append('        tw = w // 3')
    lines.append('        canvas = np.full((h, tw), bg, dtype=int)')
    lines.append('        canvas[:, :] = g[:, :tw]')
    lines.append('    return canvas.tolist()')
    return '\n'.join(lines) + '\n'
