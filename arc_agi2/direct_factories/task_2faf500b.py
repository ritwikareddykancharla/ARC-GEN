def build_program(d4, palette):
    bg = int(palette[0])
    body = int(palette[9])
    seam = int(palette[6])
    tie_vertical = ((int(d4) % 4) % 2 == 0)
    lines = [
        'import numpy as np',
        'from collections import deque',
        '',
        'BG = %d' % bg,
        'BODY = %d' % body,
        'SEAM = %d' % seam,
        'TIE_VERTICAL = %s' % ('True' if tie_vertical else 'False'),
        '',
        'def _comps(mask):',
        '    h, w = mask.shape',
        '    seen = np.zeros((h, w), bool)',
        '    out = []',
        '    for y in range(h):',
        '        for x in range(w):',
        '            if mask[y, x] and not seen[y, x]:',
        '                q = deque([(y, x)])',
        '                seen[y, x] = True',
        '                cells = []',
        '                while q:',
        '                    cy, cx = q.popleft()',
        '                    cells.append((cy, cx))',
        '                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):',
        '                        ny, nx = cy + dy, cx + dx',
        '                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:',
        '                            seen[ny, nx] = True',
        '                            q.append((ny, nx))',
        '                out.append(sorted(cells))',
        '    return out',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    H, W = g.shape',
        '    out = np.full_like(g, BG)',
        '    for blk in _comps(g != BG):',
        '        seam_cells = [(y, x) for (y, x) in blk if g[y, x] == SEAM]',
        '        if not seam_cells:',
        '            for (y, x) in blk:',
        '                out[y, x] = g[y, x]',
        '            continue',
        '        rows = set(y for (y, x) in blk)',
        '        cols = set(x for (y, x) in blk)',
        '        rc = {}',
        '        cc = {}',
        '        for (y, x) in seam_cells:',
        '            rc[y] = rc.get(y, 0) + 1',
        '            cc[x] = cc.get(x, 0) + 1',
        '        seam_horizontal = all(cc.get(c, 0) == 1 for c in cols)',
        '        seam_vertical = all(rc.get(r, 0) == 1 for r in rows)',
        '        sy = float(np.mean([c[0] for c in seam_cells]))',
        '        sx = float(np.mean([c[1] for c in seam_cells]))',
        '        bmask = np.zeros((H, W), bool)',
        '        for (y, x) in blk:',
        '            if g[y, x] != SEAM:',
        '                bmask[y, x] = True',
        '        for piece in _comps(bmask):',
        '            py = float(np.mean([c[0] for c in piece]))',
        '            px = float(np.mean([c[1] for c in piece]))',
        '            dy = py - sy',
        '            dx = px - sx',
        '            if seam_horizontal and not seam_vertical:',
        '                vertical = True',
        '            elif seam_vertical and not seam_horizontal:',
        '                vertical = False',
        '            else:',
        '                if abs(abs(dy) - abs(dx)) < 1e-9:',
        '                    vertical = TIE_VERTICAL',
        '                else:',
        '                    vertical = abs(dy) > abs(dx)',
        '            if vertical:',
        '                my, mx = (1 if dy > 0 else -1), 0',
        '            else:',
        '                my, mx = 0, (1 if dx > 0 else -1)',
        '            for (y, x) in piece:',
        '                ny, nx = y + my, x + mx',
        '                if 0 <= ny < H and 0 <= nx < W:',
        '                    out[ny, nx] = g[y, x]',
        '    return out.tolist()',
    ]
    return '\n'.join(lines) + '\n'
