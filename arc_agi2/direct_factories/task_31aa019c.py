def build_program(d4, palette):
    bg = int(palette[0])
    ring = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('RING = %d' % ring)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    counts = {}')
    lines.append('    order = []')
    lines.append('    for v in g.ravel().tolist():')
    lines.append('        if v == BG:')
    lines.append('            continue')
    lines.append('        if v not in counts:')
    lines.append('            counts[v] = 0')
    lines.append('            order.append(v)')
    lines.append('        counts[v] += 1')
    lines.append('    out = np.full_like(g, BG)')
    lines.append('    if not counts:')
    lines.append('        return out.tolist()')
    lines.append('    m = min(counts.values())')
    lines.append('    cands = [c for c in order if counts[c] == m]')
    lines.append('    c = cands[0]')
    lines.append('    pts = np.argwhere(g == c)')
    lines.append('    for p in pts:')
    lines.append('        y, x = int(p[0]), int(p[1])')
    lines.append('        for dy in (-1, 0, 1):')
    lines.append('            for dx in (-1, 0, 1):')
    lines.append('                yy, xx = y + dy, x + dx')
    lines.append('                if 0 <= yy < H and 0 <= xx < W:')
    lines.append('                    out[yy, xx] = RING')
    lines.append('    for p in pts:')
    lines.append('        out[int(p[0]), int(p[1])] = c')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
