def build_program(d4, palette):
    k = int(d4) % 4
    split_cols = (k % 2 == 1)
    bg = int(palette[0])
    fill = int(palette[6])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('FILL = %d' % fill)
    lines.append('SPLIT_COLS = %s' % ('True' if split_cols else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    if SPLIT_COLS:')
    lines.append('        half = w // 2')
    lines.append('        a = g[:, :half] != BG')
    lines.append('        b = g[:, half:half * 2] != BG')
    lines.append('        out = np.full((h, half), BG, dtype=int)')
    lines.append('    else:')
    lines.append('        half = h // 2')
    lines.append('        a = g[:half, :] != BG')
    lines.append('        b = g[half:half * 2, :] != BG')
    lines.append('        out = np.full((half, w), BG, dtype=int)')
    lines.append('    out[a & ~b] = FILL')
    lines.append('    out[b & ~a] = FILL')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
