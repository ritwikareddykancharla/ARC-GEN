def build_program(d4, palette):
    marker = int(palette[8])
    src = int(palette[1])
    dst = int(palette[3])
    lines = []
    lines.append('MARKER = %d' % marker)
    lines.append('SRC = %d' % src)
    lines.append('DST = %d' % dst)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    h = len(g)')
    lines.append('    if h == 0:')
    lines.append('        return g')
    lines.append('    w = len(g[0])')
    lines.append('    rows = [r for r in range(h) for c in range(w) if g[r][c] == MARKER]')
    lines.append('    cols = [c for r in range(h) for c in range(w) if g[r][c] == MARKER]')
    lines.append('    if not rows:')
    lines.append('        return g')
    lines.append('    r0, r1 = min(rows), max(rows)')
    lines.append('    c0, c1 = min(cols), max(cols)')
    lines.append('    for r in range(r0, r1 + 1):')
    lines.append('        for c in range(c0, c1 + 1):')
    lines.append('            if g[r][c] == SRC:')
    lines.append('                g[r][c] = DST')
    lines.append('    return g')
    return '\n'.join(lines) + '\n'
