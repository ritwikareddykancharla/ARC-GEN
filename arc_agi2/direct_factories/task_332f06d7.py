def build_program(d4, palette):
    d4 = int(d4)
    base_dirs = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    dirs = []
    for dy, dx in base_dirs:
        if d4 >= 4:
            dx = -dx
        for _ in range(d4 % 4):
            dy, dx = dx, -dy
        dirs.append((dy, dx))
    wall = int(palette[3])
    path = int(palette[1])
    mover = int(palette[0])
    goal = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('WALL = ' + repr(wall))
    lines.append('PATH = ' + repr(path))
    lines.append('MOVER = ' + repr(mover))
    lines.append('GOAL = ' + repr(goal))
    lines.append('DIRS = ' + repr(tuple(dirs)))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    z = np.argwhere(g == MOVER)')
    lines.append('    if len(z) == 0:')
    lines.append('        return g.tolist()')
    lines.append('    y0, x0 = (int(v) for v in z.min(0))')
    lines.append('    y1, x1 = (int(v) for v in z.max(0))')
    lines.append('    s = max(y1 - y0, x1 - x0) + 1')
    lines.append('    t = np.argwhere(g == GOAL)')
    lines.append('    tgt = None')
    lines.append('    if len(t) > 0:')
    lines.append('        tgt = (int(t[:, 0].min()), int(t[:, 1].min()))')
    lines.append('    blocked = (g == WALL)')
    lines.append('    def ok(y, x):')
    lines.append('        if y < 0 or x < 0 or y + s > H or x + s > W:')
    lines.append('            return False')
    lines.append('        return not blocked[y:y + s, x:x + s].any()')
    lines.append('    start = (y0, x0)')
    lines.append('    dist = {start: 0}')
    lines.append('    order = [start]')
    lines.append('    q = deque([start])')
    lines.append('    while q:')
    lines.append('        p = q.popleft()')
    lines.append('        for dy, dx in DIRS:')
    lines.append('            n = (p[0] + dy, p[1] + dx)')
    lines.append('            if n not in dist and ok(n[0], n[1]):')
    lines.append('                dist[n] = dist[p] + 1')
    lines.append('                order.append(n)')
    lines.append('                q.append(n)')
    lines.append('    if tgt is not None and tgt in dist:')
    lines.append('        dest = tgt')
    lines.append('    else:')
    lines.append('        m = max(dist.values())')
    lines.append('        dest = [k for k in order if dist[k] == m][0]')
    lines.append('    out = g.copy()')
    lines.append('    out[z[:, 0], z[:, 1]] = PATH')
    lines.append('    out[dest[0]:dest[0] + s, dest[1]:dest[1] + s] = MOVER')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
