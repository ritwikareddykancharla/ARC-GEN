def build_program(d4, palette):
    d4 = int(d4)
    # Original split is along rows (divider = full row). Row reversal keeps rows as rows;
    # an odd number of clockwise quarter turns turns the divider row into a divider column.
    axis = 0 if (d4 % 4) in (0, 2) else 1
    red = int(palette[2])
    div = int(palette[4])
    bg = int(palette[0])
    on = int(palette[3])
    src = []
    src.append('import numpy as np')
    src.append('')
    src.append('AXIS = %d' % axis)
    src.append('RED = %d' % red)
    src.append('DIV = %d' % div)
    src.append('BG = %d' % bg)
    src.append('ON = %d' % on)
    src.append('')
    src.append('def _xor_panels(a, b):')
    src.append('    return np.where((a == RED) ^ (b == RED), ON, BG).astype(int)')
    src.append('')
    src.append('def solve(demonstrations, grid):')
    src.append('    g = np.array(grid, dtype=int)')
    src.append('    h, w = g.shape')
    src.append('    if AXIS == 0:')
    src.append('        cut = None')
    src.append('        for y in range(h):')
    src.append('            if np.all(g[y, :] == DIV):')
    src.append('                cut = y')
    src.append('                break')
    src.append('        if cut is None:')
    src.append('            cut = h // 2')
    src.append('        first = g[:cut, :]')
    src.append('        second = g[cut + 1:, :]')
    src.append('        n = min(first.shape[0], second.shape[0])')
    src.append('        out = _xor_panels(first[:n, :], second[:n, :])')
    src.append('    else:')
    src.append('        cut = None')
    src.append('        for x in range(w):')
    src.append('            if np.all(g[:, x] == DIV):')
    src.append('                cut = x')
    src.append('                break')
    src.append('        if cut is None:')
    src.append('            cut = w // 2')
    src.append('        first = g[:, :cut]')
    src.append('        second = g[:, cut + 1:]')
    src.append('        n = min(first.shape[1], second.shape[1])')
    src.append('        out = _xor_panels(first[:, :n], second[:, :n])')
    src.append('    return out.tolist()')
    src.append('')
    return '\n'.join(src)
