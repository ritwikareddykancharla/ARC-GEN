def build_program(d4, palette):
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter, deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('')
    lines.append('def _components(mask):')
    lines.append('    h, w = mask.shape')
    lines.append('    seen = np.zeros_like(mask, dtype=bool)')
    lines.append('    comps = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if mask[y, x] and not seen[y, x]:')
    lines.append('                q = deque([(y, x)])')
    lines.append('                seen[y, x] = True')
    lines.append('                cells = []')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('                comps.append(cells)')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    bg = BG')
    lines.append('    if not np.any(g == bg):')
    lines.append('        vals, cnts = np.unique(g, return_counts=True)')
    lines.append('        bg = int(vals[np.argmax(cnts)])')
    lines.append('    comps = _components(g != bg)')
    lines.append('    if not comps:')
    lines.append('        return g.tolist()')
    lines.append('    objs = []')
    lines.append('    for cells in comps:')
    lines.append('        ys = [c[0] for c in cells]')
    lines.append('        xs = [c[1] for c in cells]')
    lines.append('        objs.append((len(cells), min(ys), min(xs), max(ys), max(xs)))')
    lines.append('    objs.sort(key=lambda o: (o[1], o[2]))')
    lines.append('    cnt = Counter(o[0] for o in objs)')
    lines.append('    uniq = [o for o in objs if cnt[o[0]] == 1]')
    lines.append('    chosen = uniq[0] if uniq else min(objs, key=lambda o: o[0])')
    lines.append('    _, y0, x0, y1, x1 = chosen')
    lines.append('    return g[y0:y1 + 1, x0:x1 + 1].tolist()')
    return '\n'.join(lines) + '\n'
