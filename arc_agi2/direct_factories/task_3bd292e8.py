def build_program(d4, palette):
    def mapc(ry, rx):
        if d4 >= 4:
            rx = 1 - rx
        for _ in range(d4 % 4):
            ry, rx = rx, 1 - ry
        return (ry, rx)
    A = mapc(1, 0)
    B = mapc(0, 0)
    C = mapc(0, 1)
    bg = int(palette[7])
    first = int(palette[5])
    second = int(palette[3])
    lines = []
    lines.append('from collections import deque')
    lines.append('BG = %d' % bg)
    lines.append('FIRST = %d' % first)
    lines.append('SECOND = %d' % second)
    lines.append('CA = (%d, %d)' % A)
    lines.append('CB = (%d, %d)' % B)
    lines.append('CC = (%d, %d)' % C)
    lines.append('')
    lines.append('def _seg(p, q, H, W, include_end):')
    lines.append('    y0, x0 = p[0] * (H - 1), p[1] * (W - 1)')
    lines.append('    y1, x1 = q[0] * (H - 1), q[1] * (W - 1)')
    lines.append('    n = max(abs(y1 - y0), abs(x1 - x0))')
    lines.append('    dy = (y1 > y0) - (y1 < y0)')
    lines.append('    dx = (x1 > x0) - (x1 < x0)')
    lines.append('    m = n + 1 if include_end else n')
    lines.append('    return [(y0 + dy * i, x0 + dx * i) for i in range(m)]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    if H == 0 or W == 0:')
    lines.append('        return g')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    filled = [[False] * W for _ in range(H)]')
    lines.append('    walk = _seg(CA, CB, H, W, False) + _seg(CB, CC, H, W, True)')
    lines.append('    toggle = 0')
    lines.append('    for (sy, sx) in walk:')
    lines.append('        if not (0 <= sy < H and 0 <= sx < W):')
    lines.append('            continue')
    lines.append('        if g[sy][sx] != BG or filled[sy][sx]:')
    lines.append('            continue')
    lines.append('        colour = SECOND if toggle else FIRST')
    lines.append('        q = deque([(sy, sx)])')
    lines.append('        filled[sy][sx] = True')
    lines.append('        while q:')
    lines.append('            y, x = q.popleft()')
    lines.append('            out[y][x] = colour')
    lines.append('            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                ny, nx = y + dy, x + dx')
    lines.append('                if 0 <= ny < H and 0 <= nx < W and not filled[ny][nx] and g[ny][nx] == BG:')
    lines.append('                    filled[ny][nx] = True')
    lines.append('                    q.append((ny, nx))')
    lines.append('        toggle ^= 1')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
