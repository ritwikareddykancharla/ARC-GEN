def build_program(d4, palette):
    zero = int(palette[0])
    fill = int(palette[6])
    lines = []
    lines.append('ZERO = %d' % zero)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    best = None')
    lines.append('    for r1 in range(H):')
    lines.append('        colok = [True] * W')
    lines.append('        for r2 in range(r1, H):')
    lines.append('            row = g[r2]')
    lines.append('            for c in range(W):')
    lines.append('                if row[c] != ZERO:')
    lines.append('                    colok[c] = False')
    lines.append('            if r2 == r1:')
    lines.append('                continue')
    lines.append('            h = r2 - r1 + 1')
    lines.append('            run = 0')
    lines.append('            for c in range(W):')
    lines.append('                if colok[c]:')
    lines.append('                    run += 1')
    lines.append('                else:')
    lines.append('                    run = 0')
    lines.append('                if run >= 2:')
    lines.append('                    area = h * run')
    lines.append('                    if best is None or area > best[0]:')
    lines.append('                        best = (area, r1, c - run + 1, r2, c)')
    lines.append('    out = [list(row) for row in g]')
    lines.append('    if best is not None:')
    lines.append('        _, y0, x0, y1, x1 = best')
    lines.append('        for r in range(y0, y1 + 1):')
    lines.append('            for c in range(x0, x1 + 1):')
    lines.append('                out[r][c] = FILL')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
