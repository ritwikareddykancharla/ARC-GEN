def build_program(d4, palette):
    grey = int(palette[5])
    vertical = (int(d4) % 2 == 0)
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('GREY = %d' % grey)
    lines.append('VERTICAL_BARS = %s' % ('True' if vertical else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    ys, xs = np.nonzero(g == GREY)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return g.tolist()')
    lines.append('    r0, r1 = int(ys.min()), int(ys.max())')
    lines.append('    c0, c1 = int(xs.min()), int(xs.max())')
    lines.append('    if VERTICAL_BARS:')
    lines.append('        # bars run top-to-bottom; caps sit one row above and below')
    lines.append('        r0 = max(r0 - 1, 0)')
    lines.append('        r1 = min(r1 + 1, H - 1)')
    lines.append('    else:')
    lines.append('        # bars run left-to-right; caps sit one column left and right')
    lines.append('        c0 = max(c0 - 1, 0)')
    lines.append('        c1 = min(c1 + 1, W - 1)')
    lines.append('    out = g[r0:r1 + 1, c0:c1 + 1].copy()')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
