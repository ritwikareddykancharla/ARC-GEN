def build_program(d4, palette):
    d4 = int(d4)
    frame = int(palette[1])
    corner = int(palette[7])
    cw = d4 >= 4
    horiz = (d4 % 4) in (1, 3)
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('FRAME = %d' % frame)
    lines.append('CORNER = %d' % corner)
    lines.append('TILE_CW = %s' % ('True' if cw else 'False'))
    lines.append('HORIZ = %s' % ('True' if horiz else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    tile = np.rot90(g, -1) if TILE_CW else np.rot90(g, 1)')
    lines.append('    h, w = tile.shape')
    lines.append('    if not HORIZ:')
    lines.append('        H, W = 2 * h + 3, w + 2')
    lines.append('        out = np.full((H, W), CORNER, dtype=int)')
    lines.append('        for r in (0, h + 1, 2 * h + 2):')
    lines.append('            out[r, 1:W - 1] = FRAME')
    lines.append('        for c in (0, W - 1):')
    lines.append('            out[1:h + 1, c] = FRAME')
    lines.append('            out[h + 2:2 * h + 2, c] = FRAME')
    lines.append('        out[1:h + 1, 1:w + 1] = tile')
    lines.append('        out[h + 2:2 * h + 2, 1:w + 1] = tile')
    lines.append('    else:')
    lines.append('        H, W = h + 2, 2 * w + 3')
    lines.append('        out = np.full((H, W), CORNER, dtype=int)')
    lines.append('        for c in (0, w + 1, 2 * w + 2):')
    lines.append('            out[1:H - 1, c] = FRAME')
    lines.append('        for r in (0, H - 1):')
    lines.append('            out[r, 1:w + 1] = FRAME')
    lines.append('            out[r, w + 2:2 * w + 2] = FRAME')
    lines.append('        out[1:h + 1, 1:w + 1] = tile')
    lines.append('        out[1:h + 1, w + 2:2 * w + 2] = tile')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
