def build_program(d4, palette):
    dirs = [(-1, 0), (0, 1), (1, 0), (0, -1)]
    dy, dx = dirs[d4 % 4]
    bg = int(palette[0])
    blue = int(palette[1])
    lines = []
    lines.append('BG = %d' % bg)
    lines.append('RIM = %d' % blue)
    lines.append('DY = %d' % dy)
    lines.append('DX = %d' % dx)
    lines.append('')
    lines.append('def _components(g, H, W):')
    lines.append('    seen = [[False] * W for _ in range(H)]')
    lines.append('    comps = []')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y][x] == RIM and not seen[y][x]:')
    lines.append('                stack = [(y, x)]')
    lines.append('                seen[y][x] = True')
    lines.append('                cells = []')
    lines.append('                while stack:')
    lines.append('                    cy, cx = stack.pop()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for sy, sx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + sy, cx + sx')
    lines.append('                        if 0 <= ny < H and 0 <= nx < W and not seen[ny][nx] and g[ny][nx] == RIM:')
    lines.append('                            seen[ny][nx] = True')
    lines.append('                            stack.append((ny, nx))')
    lines.append('                comps.append(cells)')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    orig = [row[:] for row in g]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    for cells in _components(orig, H, W):')
    lines.append('        y0 = min(c[0] for c in cells)')
    lines.append('        y1 = max(c[0] for c in cells)')
    lines.append('        x0 = min(c[1] for c in cells)')
    lines.append('        x1 = max(c[1] for c in cells)')
    lines.append('        seed = None')
    lines.append('        for y in range(y0, y1 + 1):')
    lines.append('            for x in range(x0, x1 + 1):')
    lines.append('                v = orig[y][x]')
    lines.append('                if v != BG and v != RIM and seed is None:')
    lines.append('                    seed = v')
    lines.append('        if seed is None:')
    lines.append('            continue')
    lines.append('        for y in range(y0, y1 + 1):')
    lines.append('            for x in range(x0, x1 + 1):')
    lines.append('                if orig[y][x] == BG:')
    lines.append('                    g[y][x] = seed')
    lines.append('        # liquid overflows through the opening (fixed visible direction) into a lid line')
    lines.append('        if DY == -1:')
    lines.append('            lid = [(y0 - 1, x) for x in range(x0, x1 + 1)]')
    lines.append('        elif DY == 1:')
    lines.append('            lid = [(y1 + 1, x) for x in range(x0, x1 + 1)]')
    lines.append('        elif DX == -1:')
    lines.append('            lid = [(y, x0 - 1) for y in range(y0, y1 + 1)]')
    lines.append('        else:')
    lines.append('            lid = [(y, x1 + 1) for y in range(y0, y1 + 1)]')
    lines.append('        for (ly, lx) in lid:')
    lines.append('            if 0 <= ly < H and 0 <= lx < W:')
    lines.append('                g[ly][lx] = seed')
    lines.append('    return g')
    return '\n'.join(lines) + '\n'
