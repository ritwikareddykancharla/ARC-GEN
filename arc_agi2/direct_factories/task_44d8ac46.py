def build_program(d4, palette):
    bg = int(palette[0])
    fill = int(palette[2])
    lines = []
    lines.append('from collections import deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('FILL = %d' % fill)
    lines.append('# D4 index %d: rule (fill enclosed solid-square background holes) is D4-invariant;' % int(d4))
    lines.append('# square bounding boxes, solidity and border contact are preserved by every rotation/reflection.')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    seen = [[False] * W for _ in range(H)]')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y][x] != BG or seen[y][x]:')
    lines.append('                continue')
    lines.append('            seen[y][x] = True')
    lines.append('            q = deque([(y, x)])')
    lines.append('            cells = []')
    lines.append('            while q:')
    lines.append('                cy, cx = q.popleft()')
    lines.append('                cells.append((cy, cx))')
    lines.append('                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                    ny, nx = cy + dy, cx + dx')
    lines.append('                    if 0 <= ny < H and 0 <= nx < W and not seen[ny][nx] and g[ny][nx] == BG:')
    lines.append('                        seen[ny][nx] = True')
    lines.append('                        q.append((ny, nx))')
    lines.append('            if any(cy in (0, H - 1) or cx in (0, W - 1) for cy, cx in cells):')
    lines.append('                continue')
    lines.append('            ys = [c[0] for c in cells]')
    lines.append('            xs = [c[1] for c in cells]')
    lines.append('            h = max(ys) - min(ys) + 1')
    lines.append('            w = max(xs) - min(xs) + 1')
    lines.append('            if h == w and len(cells) == h * w:')
    lines.append('                for cy, cx in cells:')
    lines.append('                    out[cy][cx] = FILL')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
