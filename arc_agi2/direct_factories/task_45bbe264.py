def build_program(d4, palette):
    bg = int(palette[0])
    cross = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('CROSS = %d' % cross)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    seeds = [(r, c, int(g[r, c])) for r in range(H) for c in range(W) if g[r, c] != BG]')
    lines.append('    out = np.full((H, W), BG, dtype=int)')
    lines.append('    col_owner = -np.ones((H, W), dtype=int)')
    lines.append('    # vertical lines through every seed, in the seed colour')
    lines.append('    for i, (r, c, col) in enumerate(seeds):')
    lines.append('        out[:, c] = col')
    lines.append('        col_owner[:, c] = i')
    lines.append('    # horizontal lines; crossing a different seed\'s vertical line -> CROSS')
    lines.append('    for i, (r, c, col) in enumerate(seeds):')
    lines.append('        for x in range(W):')
    lines.append('            o = col_owner[r, x]')
    lines.append('            if o >= 0 and o != i:')
    lines.append('                out[r, x] = CROSS')
    lines.append('            else:')
    lines.append('                out[r, x] = col')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
