def build_program(d4, palette):
    bg = int(palette[0])
    pat = int(palette[2])
    box = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('PAT = %d' % pat)
    lines.append('BOX = %d' % box)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    ys, xs = np.where(g == BOX)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return g.tolist()')
    lines.append('    sy = int(ys.min() + ys.max())')
    lines.append('    sx = int(xs.min() + xs.max())')
    lines.append('    out = g.copy()')
    lines.append('    py, px = np.where(g == PAT)')
    lines.append('    for y, x in zip(py.tolist(), px.tolist()):')
    lines.append('        for ny, nx in ((y, sx - x), (sy - y, x), (sy - y, sx - x)):')
    lines.append('            if 0 <= ny < H and 0 <= nx < W and out[ny, nx] == BG:')
    lines.append('                out[ny, nx] = PAT')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
