def build_program(d4, palette):
    corner = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('CORNER = %d' % corner)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    out = np.full((h + 2, w + 2), CORNER, dtype=int)')
    lines.append('    out[1:h + 1, 1:w + 1] = g')
    lines.append('    out[0, 1:w + 1] = g[0, :]')
    lines.append('    out[h + 1, 1:w + 1] = g[h - 1, :]')
    lines.append('    out[1:h + 1, 0] = g[:, 0]')
    lines.append('    out[1:h + 1, w + 1] = g[:, w - 1]')
    lines.append('    out[0, 0] = CORNER')
    lines.append('    out[0, w + 1] = CORNER')
    lines.append('    out[h + 1, 0] = CORNER')
    lines.append('    out[h + 1, w + 1] = CORNER')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
