def build_program(d4, palette):
    # Clockwise rotation maps the original top side to top, right, bottom, left
    # for k = 0..3. A horizontal pre-flip (d4 >= 4) keeps the top side on top.
    side = ('top', 'right', 'bottom', 'left')[d4 % 4]
    bg = int(palette[0])
    wall = int(palette[5])
    fill = int(palette[2])
    lines = [
        "SIDE = " + repr(side),
        "BG = " + repr(bg),
        "WALL = " + repr(wall),
        "FILL = " + repr(fill),
        "",
        "def solve(demonstrations, grid):",
        "    g = [[int(v) for v in r] for r in grid]",
        "    H = len(g)",
        "    W = len(g[0]) if H else 0",
        "    out = [r[:] for r in g]",
        "    seen = [[False] * W for _ in range(H)]",
        "    comps = []",
        "    for y in range(H):",
        "        for x in range(W):",
        "            if g[y][x] == WALL and not seen[y][x]:",
        "                stack = [(y, x)]",
        "                seen[y][x] = True",
        "                cells = []",
        "                while stack:",
        "                    cy, cx = stack.pop()",
        "                    cells.append((cy, cx))",
        "                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):",
        "                        ny, nx = cy + dy, cx + dx",
        "                        if 0 <= ny < H and 0 <= nx < W and not seen[ny][nx] and g[ny][nx] == WALL:",
        "                            seen[ny][nx] = True",
        "                            stack.append((ny, nx))",
        "                comps.append(cells)",
        "    for cells in comps:",
        "        ys = [c[0] for c in cells]",
        "        xs = [c[1] for c in cells]",
        "        y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)",
        "        if SIDE == 'top':",
        "            edge = [(y0, x) for x in range(x0, x1 + 1)]",
        "            out_d = (-1, 0)",
        "            along = (0, 1)",
        "            lo, hi = x0, x1",
        "        elif SIDE == 'bottom':",
        "            edge = [(y1, x) for x in range(x0, x1 + 1)]",
        "            out_d = (1, 0)",
        "            along = (0, 1)",
        "            lo, hi = x0, x1",
        "        elif SIDE == 'left':",
        "            edge = [(y, x0) for y in range(y0, y1 + 1)]",
        "            out_d = (0, -1)",
        "            along = (1, 0)",
        "            lo, hi = y0, y1",
        "        else:",
        "            edge = [(y, x1) for y in range(y0, y1 + 1)]",
        "            out_d = (0, 1)",
        "            along = (1, 0)",
        "            lo, hi = y0, y1",
        "        gaps = [c for c in edge if g[c[0]][c[1]] == BG]",
        "        if not gaps:",
        "            continue",
        "        gy, gx = gaps[0]",
        "        for y in range(y0, y1 + 1):",
        "            for x in range(x0, x1 + 1):",
        "                if out[y][x] == BG:",
        "                    out[y][x] = FILL",
        "        pos = gx if along == (0, 1) else gy",
        "        centre = (lo + hi) / 2.0",
        "        s = 1 if pos < centre else -1",
        "        sy, sx = along[0] * s, along[1] * s",
        "        ly, lx = gy + out_d[0], gx + out_d[1]",
        "        while 0 <= ly < H and 0 <= lx < W:",
        "            if out[ly][lx] == BG:",
        "                out[ly][lx] = FILL",
        "            ly += sy",
        "            lx += sx",
        "    return out",
        "",
    ]
    return "\n".join(lines)
