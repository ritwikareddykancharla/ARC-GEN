def build_program(d4, palette):
    bg = int(palette[8])
    side = {0: 'left', 1: 'top', 2: 'right', 3: 'bottom',
            4: 'right', 5: 'bottom', 6: 'left', 7: 'top'}[int(d4) % 8]
    conds = {
        'left': 'x - x0 < 2',
        'right': 'x1 - x < 2',
        'top': 'y - y0 < 2',
        'bottom': 'y1 - y < 2',
    }
    cond = conds[side]
    lines = [
        'import numpy as np',
        'from collections import deque',
        '',
        'BG = %d' % bg,
        '# Trim side in visible coordinates: %s' % side,
        '',
        'def _components(g):',
        '    h, w = g.shape',
        '    seen = np.zeros((h, w), dtype=bool)',
        '    comps = []',
        '    for sy in range(h):',
        '        for sx in range(w):',
        '            if seen[sy, sx] or int(g[sy, sx]) == BG:',
        '                continue',
        '            col = int(g[sy, sx])',
        '            seen[sy, sx] = True',
        '            q = deque([(sy, sx)])',
        '            cells = []',
        '            while q:',
        '                cy, cx = q.popleft()',
        '                cells.append((cy, cx))',
        '                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):',
        '                    ny, nx = cy + dy, cx + dx',
        '                    if 0 <= ny < h and 0 <= nx < w and not seen[ny, nx] and int(g[ny, nx]) == col:',
        '                        seen[ny, nx] = True',
        '                        q.append((ny, nx))',
        '            comps.append(cells)',
        '    return comps',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    out = g.copy()',
        '    for cells in _components(g):',
        '        ys = [c[0] for c in cells]',
        '        xs = [c[1] for c in cells]',
        '        y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)',
        '        for y, x in cells:',
        '            if ' + cond + ':',
        '                out[y, x] = BG',
        '    return out.tolist()',
        '',
    ]
    return '\n'.join(lines)
