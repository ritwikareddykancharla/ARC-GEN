def build_program(d4, palette):
    e = (1, 0)
    s = (0, 1)
    if d4 >= 4:
        e = (e[0], -e[1])
        s = (s[0], -s[1])
    for _ in range(d4 % 4):
        e = (e[1], -e[0])
        s = (s[1], -s[0])
    if e[0] != 0:
        axis = 0
        fwd = e[0] > 0
        sgn = s[1]
    else:
        axis = 1
        fwd = e[1] > 0
        sgn = s[0]
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('')
    lines.append('AXIS = %d' % axis)
    lines.append('FWD = %s' % ('True' if fwd else 'False'))
    lines.append('SGN = %d' % sgn)
    lines.append('TARGET = 10')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    bg = int(Counter(g.ravel().tolist()).most_common(1)[0][0])')
    lines.append('    nr, nc = g.shape')
    lines.append('    L = nr if AXIS == 0 else nc')
    lines.append('    W = nc if AXIS == 0 else nr')
    lines.append('    def get_line(arr, k, tot):')
    lines.append('        idx = k if FWD else tot - 1 - k')
    lines.append('        return arr[idx, :].copy() if AXIS == 0 else arr[:, idx].copy()')
    lines.append('    def set_line(arr, k, tot, vals):')
    lines.append('        idx = k if FWD else tot - 1 - k')
    lines.append('        if AXIS == 0:')
    lines.append('            arr[idx, :] = vals')
    lines.append('        else:')
    lines.append('            arr[:, idx] = vals')
    lines.append('    def shift(line, d):')
    lines.append('        r = np.full(W, bg, dtype=int)')
    lines.append('        for x in range(W):')
    lines.append('            nx = x + d')
    lines.append('            if 0 <= nx < W:')
    lines.append('                r[nx] = line[x]')
    lines.append('        return r')
    lines.append('    best = None')
    lines.append('    order = sorted(range(-W + 1, W), key=lambda d: (abs(d), d * SGN))')
    lines.append('    for dy in range(1, L):')
    lines.append('        for d in order:')
    lines.append('            ok = True')
    lines.append('            for y in range(dy, L):')
    lines.append('                if not np.array_equal(shift(get_line(g, y - dy, L), d), get_line(g, y, L)):')
    lines.append('                    ok = False')
    lines.append('                    break')
    lines.append('            if ok:')
    lines.append('                best = (dy, d)')
    lines.append('                break')
    lines.append('        if best:')
    lines.append('            break')
    lines.append('    if best is None:')
    lines.append('        best = (L, 0)')
    lines.append('    dy, d = best')
    lines.append('    Lout = max(TARGET, L)')
    lines.append('    shape = (Lout, W) if AXIS == 0 else (W, Lout)')
    lines.append('    out = np.full(shape, bg, dtype=int)')
    lines.append('    for k in range(L):')
    lines.append('        set_line(out, k, Lout, get_line(g, k, L))')
    lines.append('    for k in range(L, Lout):')
    lines.append('        set_line(out, k, Lout, shift(get_line(out, k - dy, Lout), d))')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
