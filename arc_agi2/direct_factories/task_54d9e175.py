def build_program(d4, palette):
    pal = [int(v) for v in palette]
    bg = pal[0]
    div = pal[5]
    table = {pal[c]: pal[c + 5] for c in range(1, 5)}
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DIV = %d' % div)
    lines.append('TABLE = %r' % (table,))
    lines.append('D4 = %d' % int(d4))
    lines.append('')
    lines.append('def _spans(cuts, n):')
    lines.append('    edges = [-1] + sorted(cuts) + [n]')
    lines.append('    out = []')
    lines.append('    for a, b in zip(edges[:-1], edges[1:]):')
    lines.append('        if b - a > 1:')
    lines.append('            out.append((a + 1, b))')
    lines.append('    return out')
    lines.append('')
    lines.append('def _panels(g):')
    lines.append('    h, w = g.shape')
    lines.append('    rcuts = [y for y in range(h) if (g[y, :] == DIV).all()]')
    lines.append('    ccuts = [x for x in range(w) if (g[:, x] == DIV).all()]')
    lines.append('    ys = _spans(rcuts, h)')
    lines.append('    xs = _spans(ccuts, w)')
    lines.append('    return [(y0, y1, x0, x1) for (y0, y1) in ys for (x0, x1) in xs]')
    lines.append('')
    lines.append('def _seed(sub):')
    lines.append('    for v in sub.ravel().tolist():')
    lines.append('        if v != BG and v != DIV:')
    lines.append('            return int(v)')
    lines.append('    return None')
    lines.append('')
    lines.append('def _learn(demonstrations):')
    lines.append('    learned = {}')
    lines.append('    for d in demonstrations or []:')
    lines.append('        try:')
    lines.append('            gi = np.array(d["input"], dtype=int)')
    lines.append('            go = np.array(d["output"], dtype=int)')
    lines.append('        except Exception:')
    lines.append('            continue')
    lines.append('        if gi.shape != go.shape:')
    lines.append('            continue')
    lines.append('        for (y0, y1, x0, x1) in _panels(gi):')
    lines.append('            s = _seed(gi[y0:y1, x0:x1])')
    lines.append('            if s is None:')
    lines.append('                continue')
    lines.append('            vals = go[y0:y1, x0:x1].ravel().tolist()')
    lines.append('            if vals and all(v == vals[0] for v in vals):')
    lines.append('                learned.setdefault(s, int(vals[0]))')
    lines.append('    return learned')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    table = dict(TABLE)')
    lines.append('    learned = _learn(demonstrations)')
    lines.append('    for k, v in learned.items():')
    lines.append('        if k not in table:')
    lines.append('            table[k] = v')
    lines.append('    for (y0, y1, x0, x1) in _panels(g):')
    lines.append('        s = _seed(g[y0:y1, x0:x1])')
    lines.append('        if s is None or s not in table:')
    lines.append('            continue')
    lines.append('        out[y0:y1, x0:x1] = table[s]')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
