def build_program(d4, palette):
    bg = int(palette[0])
    box = int(palette[1])
    fill = int(palette[8])
    lines = []
    lines.append('# Direct-coordinate solver: hollow boxes get filled, gaps leak rays outward.')
    lines.append('# Orientation code d4=%d. The rule is D4-invariant: fill the inside of every' % int(d4))
    lines.append('# box and shoot a ray perpendicular to the gapped side, away from the box.')
    lines.append('BG = %d' % bg)
    lines.append('BOX = %d' % box)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def _components(g, H, W, colour):')
    lines.append('    seen = [[False] * W for _ in range(H)]')
    lines.append('    comps = []')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y][x] == colour and not seen[y][x]:')
    lines.append('                seen[y][x] = True')
    lines.append('                stack = [(y, x)]')
    lines.append('                cells = []')
    lines.append('                while stack:')
    lines.append('                    cy, cx = stack.pop()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < H and 0 <= nx < W and not seen[ny][nx] and g[ny][nx] == colour:')
    lines.append('                            seen[ny][nx] = True')
    lines.append('                            stack.append((ny, nx))')
    lines.append('                comps.append(cells)')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [[int(v) for v in row] for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    for cells in _components(g, H, W, BOX):')
    lines.append('        ys = [c[0] for c in cells]')
    lines.append('        xs = [c[1] for c in cells]')
    lines.append('        y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)')
    lines.append('        if y1 - y0 < 2 or x1 - x0 < 2:')
    lines.append('            continue')
    lines.append('        for y in range(y0 + 1, y1):')
    lines.append('            for x in range(x0 + 1, x1):')
    lines.append('                if g[y][x] == BG:')
    lines.append('                    out[y][x] = FILL')
    lines.append('        gaps = []')
    lines.append('        for x in range(x0 + 1, x1):')
    lines.append('            if g[y0][x] == BG:')
    lines.append('                gaps.append((y0, x, -1, 0))')
    lines.append('            if g[y1][x] == BG:')
    lines.append('                gaps.append((y1, x, 1, 0))')
    lines.append('        for y in range(y0 + 1, y1):')
    lines.append('            if g[y][x0] == BG:')
    lines.append('                gaps.append((y, x0, 0, -1))')
    lines.append('            if g[y][x1] == BG:')
    lines.append('                gaps.append((y, x1, 0, 1))')
    lines.append('        for y, x, dy, dx in gaps:')
    lines.append('            while 0 <= y < H and 0 <= x < W and g[y][x] == BG:')
    lines.append('                out[y][x] = FILL')
    lines.append('                y += dy')
    lines.append('                x += dx')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
