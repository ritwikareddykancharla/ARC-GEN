def build_program(d4, palette):
    k = d4 % 4
    # Canonical: rectangles rest on the bottom edge and move UP by their own height.
    # A horizontal flip (d4>=4) leaves vertical motion unchanged. Each clockwise turn
    # rotates the motion direction: up -> right -> down -> left.
    dy, dx = [(-1, 0), (0, 1), (1, 0), (0, -1)][k]
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DY = %d' % dy)
    lines.append('DX = %d' % dx)
    lines.append('')
    lines.append('def _components(g, colour):')
    lines.append('    h, w = g.shape')
    lines.append('    seen = np.zeros((h, w), bool)')
    lines.append('    comps = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if g[y, x] == colour and not seen[y, x]:')
    lines.append('                seen[y, x] = True')
    lines.append('                q = deque([(y, x)])')
    lines.append('                cells = []')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for sy, sx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + sy, cx + sx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and not seen[ny, nx] and g[ny, nx] == colour:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('                comps.append(sorted(cells))')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    out = np.full((h, w), BG, dtype=int)')
    lines.append('    objs = []')
    lines.append('    for colour in sorted(set(g.ravel().tolist()) - {BG}):')
    lines.append('        for cells in _components(g, colour):')
    lines.append('            ys = [c[0] for c in cells]')
    lines.append('            xs = [c[1] for c in cells]')
    lines.append('            objs.append((min(ys), min(xs), max(ys), max(xs), colour, cells))')
    lines.append('    objs.sort(key=lambda o: (o[0], o[1]))')
    lines.append('    for y0, x0, y1, x1, colour, cells in objs:')
    lines.append('        # The shift equals the object extent measured along the motion axis.')
    lines.append('        if DY != 0:')
    lines.append('            n = y1 - y0 + 1')
    lines.append('        else:')
    lines.append('            n = x1 - x0 + 1')
    lines.append('        for y, x in cells:')
    lines.append('            ny, nx = y + DY * n, x + DX * n')
    lines.append('            if 0 <= ny < h and 0 <= nx < w:')
    lines.append('                out[ny, nx] = colour')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
