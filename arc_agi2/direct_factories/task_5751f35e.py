def build_program(d4, palette):
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('BG = %d' % bg)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    ys, xs = np.indices((h, w))')
    lines.append('    depth = np.minimum(np.minimum(ys, xs), np.minimum(h - 1 - ys, w - 1 - xs))')
    lines.append('    out = np.full((h, w), BG, dtype=int)')
    lines.append('    maxd = int(depth.max()) if depth.size else 0')
    lines.append('    for k in range(maxd + 1):')
    lines.append('        mask = depth == k')
    lines.append('        vals = [int(v) for v in g[mask].tolist() if int(v) != BG]')
    lines.append('        if not vals:')
    lines.append('            col = BG')
    lines.append('        else:')
    lines.append('            cnt = Counter(vals)')
    lines.append('            best = max(cnt.values())')
    lines.append('            col = None')
    lines.append('            for v in vals:')
    lines.append('                if cnt[v] == best:')
    lines.append('                    col = v')
    lines.append('        out[mask] = col')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
