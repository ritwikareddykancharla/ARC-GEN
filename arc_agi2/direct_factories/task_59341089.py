def build_program(d4, palette):
    k = d4 % 4
    vertical = (k % 2 == 1)
    reversed_order = ((k in (2, 3)) != (d4 >= 4))
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('VERTICAL = %r' % bool(vertical))
    lines.append('MIRROR_FIRST = %r' % (not reversed_order))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    if VERTICAL:')
    lines.append('        m = g[::-1, :]')
    lines.append('        out = np.zeros((4 * h, w), dtype=int)')
    lines.append('    else:')
    lines.append('        m = g[:, ::-1]')
    lines.append('        out = np.zeros((h, 4 * w), dtype=int)')
    lines.append('    if MIRROR_FIRST:')
    lines.append('        blocks = [m, g, m, g]')
    lines.append('    else:')
    lines.append('        blocks = [g, m, g, m]')
    lines.append('    for i, b in enumerate(blocks):')
    lines.append('        if VERTICAL:')
    lines.append('            out[i * h:(i + 1) * h, :] = b')
    lines.append('        else:')
    lines.append('            out[:, i * w:(i + 1) * w] = b')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
