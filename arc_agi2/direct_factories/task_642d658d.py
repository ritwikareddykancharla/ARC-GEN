def build_program(d4, palette):
    centre = int(palette[4])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('')
    lines.append('CENTRE = %d' % centre)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    counts = Counter()')
    lines.append('    for y in range(1, H - 1):')
    lines.append('        for x in range(1, W - 1):')
    lines.append('            if g[y, x] != CENTRE:')
    lines.append('                continue')
    lines.append('            nb = {int(g[y - 1, x]), int(g[y + 1, x]), int(g[y, x - 1]), int(g[y, x + 1])}')
    lines.append('            if len(nb) == 1:')
    lines.append('                counts[nb.pop()] += 1')
    lines.append('    if counts:')
    lines.append('        best = max(counts.values())')
    lines.append('        colour = min(c for c, n in counts.items() if n == best)')
    lines.append('    else:')
    lines.append('        colour = int(Counter(g.ravel().tolist()).most_common(1)[0][0])')
    lines.append('    return [[int(colour)]]')
    return '\n'.join(lines) + '\n'
