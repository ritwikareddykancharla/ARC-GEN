def build_program(d4, palette):
    bg = int(palette[0])
    lines = [
        'import numpy as np',
        '',
        'BG = ' + str(bg),
        'SLOT = 3',
        '',
        'def _offset(extent):',
        '    if extent >= SLOT:',
        '        return 0',
        '    if extent == 1:',
        '        return 1',
        '    return 0',
        '',
        'def _separated(starts):',
        '    s = sorted(starts)',
        '    for a, b in zip(s, s[1:]):',
        '        if b - a < SLOT:',
        '            return False',
        '    return True',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.asarray(grid, dtype=int)',
        '    H, W = g.shape',
        '    colors = sorted(set(np.unique(g).tolist()) - {BG})',
        '    if not colors:',
        '        return [[BG] * SLOT for _ in range(SLOT)]',
        '    shapes = []',
        '    for c in colors:',
        '        ys, xs = np.nonzero(g == c)',
        '        y0, y1 = int(ys.min()), int(ys.max())',
        '        x0, x1 = int(xs.min()), int(xs.max())',
        '        oy = y0 - _offset(y1 - y0 + 1)',
        '        ox = x0 - _offset(x1 - x0 + 1)',
        '        if H >= SLOT:',
        '            oy = max(0, min(oy, H - SLOT))',
        '        if W >= SLOT:',
        '            ox = max(0, min(ox, W - SLOT))',
        '        shapes.append((oy, ox, c, ys, xs))',
        '    oys = [s[0] for s in shapes]',
        '    oxs = [s[1] for s in shapes]',
        '    rows_sep = _separated(oys)',
        '    cols_sep = _separated(oxs)',
        '    if cols_sep and not rows_sep:',
        '        horizontal = True',
        '    elif rows_sep and not cols_sep:',
        '        horizontal = False',
        '    else:',
        '        horizontal = (max(oxs) - min(oxs)) > (max(oys) - min(oys))',
        '    if horizontal:',
        '        shapes.sort(key=lambda s: (s[1], s[0], s[2]))',
        '    else:',
        '        shapes.sort(key=lambda s: (s[0], s[1], s[2]))',
        '    n = len(shapes)',
        '    if horizontal:',
        '        out = np.full((SLOT, SLOT * n), BG, dtype=int)',
        '    else:',
        '        out = np.full((SLOT * n, SLOT), BG, dtype=int)',
        '    for i, (oy, ox, c, ys, xs) in enumerate(shapes):',
        '        by, bx = (0, i * SLOT) if horizontal else (i * SLOT, 0)',
        '        for y, x in zip(ys.tolist(), xs.tolist()):',
        '            dy, dx = y - oy, x - ox',
        '            if 0 <= dy < SLOT and 0 <= dx < SLOT:',
        '                out[by + dy, bx + dx] = c',
        '    return out.tolist()',
        '',
    ]
    return '\n'.join(lines)
