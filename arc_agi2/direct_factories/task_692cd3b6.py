def build_program(d4, palette):
    bg = int(palette[0])
    ring = int(palette[2])
    core = int(palette[5])
    fill = int(palette[4])
    lines = [
        'import numpy as np',
        '',
        'BG = %d' % bg,
        'RING = %d' % ring,
        'CORE = %d' % core,
        'FILL = %d' % fill,
        'DIRS = ((-1, 0), (1, 0), (0, -1), (0, 1))',
        '',
        'def _find_cups(g):',
        '    H, W = g.shape',
        '    cups = []',
        '    ys, xs = np.nonzero(g == CORE)',
        '    for y, x in zip(ys.tolist(), xs.tolist()):',
        '        door = None',
        '        ringn = 0',
        '        for dy, dx in DIRS:',
        '            ny, nx = y + dy, x + dx',
        '            if 0 <= ny < H and 0 <= nx < W:',
        '                v = int(g[ny, nx])',
        '                if v == BG:',
        '                    door = (ny, nx, dy, dx)',
        '                elif v == RING:',
        '                    ringn += 1',
        '        if door is None or ringn < 2:',
        '            continue',
        '        ny, nx, dy, dx = door',
        '        cups.append({"c": (y, x), "door": (ny, nx), "d": (dy, dx), "exit": (ny + dy, nx + dx)})',
        '    return cups',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    H, W = g.shape',
        '    out = g.copy()',
        '    cups = _find_cups(g)',
        '    for c in cups:',
        '        out[c["door"]] = FILL',
        '    if len(cups) != 2:',
        '        return out.tolist()',
        '    (ay, ax), (by, bx) = cups[0]["exit"], cups[1]["exit"]',
        '    Y0, Y1 = min(ay, by), max(ay, by)',
        '    X0, X1 = min(ax, bx), max(ax, bx)',
        '    mask = np.zeros((H, W), dtype=bool)',
        '    y0c, y1c = max(Y0, 0), min(Y1, H - 1)',
        '    x0c, x1c = max(X0, 0), min(X1, W - 1)',
        '    if y0c <= y1c and x0c <= x1c:',
        '        mask[y0c:y1c + 1, x0c:x1c + 1] = True',
        '    for c in cups:',
        '        ey, ex = c["exit"]',
        '        dy, dx = c["d"]',
        '        py, px = ey + dy, ex + dx',
        '        if Y0 <= py <= Y1 and X0 <= px <= X1:',
        '            continue',
        '        cy, cx = c["c"]',
        '        if dx != 0:',
        '            for y in range(cy - 1, cy + 2):',
        '                if 0 <= y < H:',
        '                    for x in range(W):',
        '                        if x != ex:',
        '                            mask[y, x] = False',
        '        else:',
        '            for x in range(cx - 1, cx + 2):',
        '                if 0 <= x < W:',
        '                    for y in range(H):',
        '                        if y != ey:',
        '                            mask[y, x] = False',
        '    out[mask & (out == BG)] = FILL',
        '    return out.tolist()',
        '',
    ]
    return '\n'.join(lines)
