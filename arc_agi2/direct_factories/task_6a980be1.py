def build_program(d4, palette):
    zero = int(palette[0])
    green = int(palette[3])
    prefer_cols = 'True' if (int(d4) % 2 == 1) else 'False'
    lines = [
        'import numpy as np',
        '',
        'ZERO = ' + str(zero),
        'GREEN = ' + str(green),
        'PREFER_COLS = ' + prefer_cols,
        '',
        'def _period(seq):',
        '    n = len(seq)',
        '    for q in range(1, n + 1):',
        '        ok = True',
        '        for i in range(n - q):',
        '            if seq[i] != seq[i + q]:',
        '                ok = False',
        '                break',
        '        if ok:',
        '            return q',
        '    return max(n, 1)',
        '',
        'def _extend(seq, length):',
        '    # seq is the interior run (index 0 <-> visible position 1); extend periodically both ways',
        '    p = _period(seq)',
        '    return [int(seq[(x - 1) % p]) for x in range(length)]',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    H, W = g.shape',
        '    if H < 3 or W < 3:',
        '        return g.tolist()',
        '    B = int(g[0, 0])',
        '    line_rows = [y for y in range(1, H - 1) if np.all(g[y, 1:W - 1] == GREEN)]',
        '    line_cols = [x for x in range(1, W - 1) if np.all(g[1:H - 1, x] == GREEN)]',
        '    horizontal = len(line_rows) >= 2',
        '    vertical = len(line_cols) >= 2',
        '    if horizontal and vertical:',
        '        horizontal = not PREFER_COLS',
        '    if not horizontal and not vertical:',
        '        return g.tolist()',
        '    res = np.full((H, W), ZERO, dtype=int)',
        '    if horizontal:',
        '        # band runs left-right between two full green rows; pattern varies along columns',
        '        r1, r2 = line_rows[0], line_rows[-1]',
        '        full = _extend([int(v) for v in g[r1 + 1, 1:W - 1]], W)',
        '        stripe = [B if v != ZERO else ZERO for v in full]',
        '        for y in range(H):',
        '            if y == r1 or y == r2:',
        '                res[y, :] = GREEN',
        '            elif r1 < y < r2:',
        '                res[y, :] = full',
        '            else:',
        '                res[y, :] = stripe',
        '    else:',
        '        # band runs top-bottom between two full green columns; pattern varies along rows',
        '        c1, c2 = line_cols[0], line_cols[-1]',
        '        full = _extend([int(v) for v in g[1:H - 1, c1 + 1]], H)',
        '        stripe = [B if v != ZERO else ZERO for v in full]',
        '        for x in range(W):',
        '            if x == c1 or x == c2:',
        '                res[:, x] = GREEN',
        '            elif c1 < x < c2:',
        '                res[:, x] = full',
        '            else:',
        '                res[:, x] = stripe',
        '    return res.tolist()',
        '',
    ]
    return '\n'.join(lines)
