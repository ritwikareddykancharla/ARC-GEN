def build_program(d4, palette):
    bg = int(palette[0])
    frame = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('FRAME = %d' % frame)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    fy, fx = np.where(g == FRAME)')
    lines.append('    if fy.size == 0:')
    lines.append('        return g.tolist()')
    lines.append('    y0, y1, x0, x1 = int(fy.min()), int(fy.max()), int(fx.min()), int(fx.max())')
    lines.append('    out = g[y0:y1 + 1, x0:x1 + 1].copy()')
    lines.append('    H, W = out.shape')
    lines.append('    if H < 3 or W < 3:')
    lines.append('        return out.tolist()')
    lines.append('    out[1:-1, 1:-1] = BG')
    lines.append('    ih, iw = H - 2, W - 2')
    lines.append('    mask = (g != BG) & (g != FRAME)')
    lines.append('    my, mx = np.where(mask)')
    lines.append('    if my.size == 0:')
    lines.append('        return out.tolist()')
    lines.append('    motif = g[int(my.min()):int(my.max()) + 1, int(mx.min()):int(mx.max()) + 1]')
    lines.append('    mh, mw = motif.shape')
    lines.append('    # motif lives in a 3x3 cell lattice; interior is 3k x 3k')
    lines.append('    ky = ih // 3 if mh <= 3 and ih % 3 == 0 else max(1, ih // mh)')
    lines.append('    kx = iw // 3 if mw <= 3 and iw % 3 == 0 else max(1, iw // mw)')
    lines.append('    if mh == 3:')
    lines.append('        ky = max(1, ih // 3)')
    lines.append('    if mw == 3:')
    lines.append('        kx = max(1, iw // 3)')
    lines.append('    scaled = np.kron(motif, np.ones((ky, kx), dtype=int))')
    lines.append('    sh = min(scaled.shape[0], ih)')
    lines.append('    sw = min(scaled.shape[1], iw)')
    lines.append('    out[1:1 + sh, 1:1 + sw] = scaled[:sh, :sw]')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
