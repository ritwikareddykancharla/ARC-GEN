def build_program(d4, palette):
    seed = int(palette[3])
    obst = int(palette[8])
    reflected = int(d4) >= 4
    lines = []
    lines.append('import numpy as np')
    lines.append('SEED = %d' % seed)
    lines.append('OBST = %d' % obst)
    lines.append('REFLECTED = %s' % ('True' if reflected else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int).copy()')
    lines.append('    H, W = g.shape')
    lines.append('    cells = sorted((int(r), int(c)) for r, c in zip(*np.where(g == SEED)))')
    lines.append('    if len(cells) < 2:')
    lines.append('        return g.tolist()')
    lines.append('    a, b = cells[0], cells[-1]')
    lines.append('    dy, dx = b[0] - a[0], b[1] - a[1]')
    lines.append('    if dy: dy = 1 if dy > 0 else -1')
    lines.append('    if dx: dx = 1 if dx > 0 else -1')
    lines.append('    def inb(y, x):')
    lines.append('        return 0 <= y < H and 0 <= x < W')
    lines.append('    def free(y, x):')
    lines.append('        return inb(y, x) and g[y, x] != OBST')
    lines.append('    # the domino has one end on the border; the snake leaves from the other end')
    lines.append('    fb = free(b[0] + dy, b[1] + dx)')
    lines.append('    fa = free(a[0] - dy, a[1] - dx)')
    lines.append('    if fb and not fa:')
    lines.append('        cur, d = b, (dy, dx)')
    lines.append('    elif fa and not fb:')
    lines.append('        cur, d = a, (-dy, -dx)')
    lines.append('    elif inb(b[0] + dy, b[1] + dx) and not inb(a[0] - dy, a[1] - dx):')
    lines.append('        cur, d = b, (dy, dx)')
    lines.append('    elif inb(a[0] - dy, a[1] - dx) and not inb(b[0] + dy, b[1] + dx):')
    lines.append('        cur, d = a, (-dy, -dx)')
    lines.append('    elif fb:')
    lines.append('        cur, d = b, (dy, dx)')
    lines.append('    else:')
    lines.append('        cur, d = a, (-dy, -dx)')
    lines.append('    steps = 0')
    lines.append('    while steps < 4 * H * W + 8:')
    lines.append('        steps += 1')
    lines.append('        ny, nx = cur[0] + d[0], cur[1] + d[1]')
    lines.append('        if not inb(ny, nx):')
    lines.append('            break')
    lines.append('        if g[ny, nx] == OBST:')
    lines.append('            cw = (d[1], -d[0])')
    lines.append('            ccw = (-d[1], d[0])')
    lines.append('            cand = [ccw, cw] if REFLECTED else [cw, ccw]')
    lines.append('            nd = None')
    lines.append('            for o in cand:')
    lines.append('                if free(cur[0] + o[0], cur[1] + o[1]):')
    lines.append('                    nd = o')
    lines.append('                    break')
    lines.append('            if nd is None:')
    lines.append('                break')
    lines.append('            d = nd')
    lines.append('            continue')
    lines.append('        g[ny, nx] = SEED')
    lines.append('        cur = (ny, nx)')
    lines.append('    return g.tolist()')
    return '\n'.join(lines) + '\n'
