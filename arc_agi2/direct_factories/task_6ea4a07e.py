def build_program(d4, palette):
    pal = [int(x) for x in palette]
    bg = pal[0]
    table = {pal[5]: pal[4], pal[8]: pal[2], pal[3]: pal[1]}
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('TABLE = %r' % (table,))
    lines.append('')
    lines.append('def _learn(demonstrations):')
    lines.append('    learned = {}')
    lines.append('    for d in demonstrations or []:')
    lines.append('        try:')
    lines.append('            a = np.array(d["input"]); b = np.array(d["output"])')
    lines.append('        except Exception:')
    lines.append('            continue')
    lines.append('        if a.shape != b.shape:')
    lines.append('            continue')
    lines.append('        inks = [int(c) for c in np.unique(a) if int(c) != BG]')
    lines.append('        if len(inks) != 1:')
    lines.append('            continue')
    lines.append('        m = a == BG')
    lines.append('        if m.any():')
    lines.append('            vals = np.unique(b[m])')
    lines.append('            if len(vals) == 1:')
    lines.append('                learned[inks[0]] = int(vals[0])')
    lines.append('    return learned')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    table = dict(TABLE)')
    lines.append('    for k, v in _learn(demonstrations).items():')
    lines.append('        if k not in table:')
    lines.append('            table[k] = v')
    lines.append('    inks = [int(c) for c in np.unique(g) if int(c) != BG]')
    lines.append('    if not inks:')
    lines.append('        return g.tolist()')
    lines.append('    ink = inks[0]')
    lines.append('    new = table.get(ink, ink)')
    lines.append('    out = g.copy()')
    lines.append('    out[g == BG] = new')
    lines.append('    out[g == ink] = BG')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
