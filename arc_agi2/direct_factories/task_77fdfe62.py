def build_program(d4, palette):
    pal = [int(x) for x in palette]
    frame = pal[1]
    cyan = pal[8]
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('FRAME = %d' % frame)
    lines.append('MARK = %d' % cyan)
    lines.append('')
    lines.append('def _bounds(g):')
    lines.append('    H, W = g.shape')
    lines.append('    full_rows = [r for r in range(H) if np.all(g[r, :] == FRAME)]')
    lines.append('    full_cols = [c for c in range(W) if np.all(g[:, c] == FRAME)]')
    lines.append('    if len(full_rows) >= 2:')
    lines.append('        r0, r1 = full_rows[0] + 1, full_rows[-1]')
    lines.append('    else:')
    lines.append('        r0, r1 = 2, H - 2')
    lines.append('    if len(full_cols) >= 2:')
    lines.append('        c0, c1 = full_cols[0] + 1, full_cols[-1]')
    lines.append('    else:')
    lines.append('        c0, c1 = 2, W - 2')
    lines.append('    if r1 <= r0 or c1 <= c0:')
    lines.append('        r0, r1, c0, c1 = 2, H - 2, 2, W - 2')
    lines.append('    return r0, r1, c0, c1')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    r0, r1, c0, c1 = _bounds(g)')
    lines.append('    inner = g[r0:r1, c0:c1]')
    lines.append('    h, w = inner.shape')
    lines.append('    hh, hw = h // 2, w // 2')
    lines.append('    tl = int(g[0, 0]); tr = int(g[0, W - 1])')
    lines.append('    bl = int(g[H - 1, 0]); br = int(g[H - 1, W - 1])')
    lines.append('    out = inner.copy()')
    lines.append('    for r in range(h):')
    lines.append('        for c in range(w):')
    lines.append('            if inner[r, c] != MARK:')
    lines.append('                continue')
    lines.append('            top = r < hh')
    lines.append('            left = c < hw')
    lines.append('            if top and left:')
    lines.append('                out[r, c] = tl')
    lines.append('            elif top:')
    lines.append('                out[r, c] = tr')
    lines.append('            elif left:')
    lines.append('                out[r, c] = bl')
    lines.append('            else:')
    lines.append('                out[r, c] = br')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
