def build_program(d4, palette):
    pal = [int(v) for v in palette]
    BG = pal[0]
    OPEN = pal[3]
    CLOSED = pal[2]
    L = []
    L.append('from collections import deque')
    L.append('')
    L.append('BG = %d' % BG)
    L.append('OPEN_COLOUR = %d' % OPEN)
    L.append('CLOSED_COLOUR = %d' % CLOSED)
    L.append('')
    L.append('def solve(demonstrations, grid):')
    L.append('    g = [list(map(int, row)) for row in grid]')
    L.append('    H = len(g)')
    L.append('    if H == 0:')
    L.append('        return g')
    L.append('    W = len(g[0])')
    L.append('    out = [row[:] for row in g]')
    L.append('    seen = [[False] * W for _ in range(H)]')
    L.append('    for sy in range(H):')
    L.append('        for sx in range(W):')
    L.append('            if g[sy][sx] != BG or seen[sy][sx]:')
    L.append('                continue')
    L.append('            seen[sy][sx] = True')
    L.append('            q = deque([(sy, sx)])')
    L.append('            cells = []')
    L.append('            touches = False')
    L.append('            while q:')
    L.append('                y, x = q.popleft()')
    L.append('                cells.append((y, x))')
    L.append('                if y == 0 or x == 0 or y == H - 1 or x == W - 1:')
    L.append('                    touches = True')
    L.append('                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    L.append('                    ny, nx = y + dy, x + dx')
    L.append('                    if 0 <= ny < H and 0 <= nx < W and not seen[ny][nx] and g[ny][nx] == BG:')
    L.append('                        seen[ny][nx] = True')
    L.append('                        q.append((ny, nx))')
    L.append('            col = OPEN_COLOUR if touches else CLOSED_COLOUR')
    L.append('            for y, x in cells:')
    L.append('                out[y][x] = col')
    L.append('    return out')
    L.append('')
    return chr(10).join(L)
