def build_program(d4, palette):
    p8 = int(palette[8])
    p3 = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('DIV = %d' % p8)
    lines.append('PAT = %d' % p3)
    lines.append('')
    lines.append('def _divider_row(g):')
    lines.append('    H, W = g.shape')
    lines.append('    full = [r for r in range(H) if np.all(g[r, :] == DIV)]')
    lines.append('    if full:')
    lines.append('        return full[0]')
    lines.append('    counts = [int(np.sum(g[r, :] == DIV)) for r in range(H)]')
    lines.append('    return int(np.argmax(counts))')
    lines.append('')
    lines.append('def _split(n, d):')
    lines.append('    before = list(range(0, d))')
    lines.append('    after = list(range(d + 1, n))')
    lines.append('    if len(before) >= len(after):')
    lines.append('        return before, after')
    lines.append('    return after, before')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    r8 = _divider_row(g)')
    lines.append('    c8 = _divider_row(g.T)')
    lines.append('    prow, krow = _split(H, r8)')
    lines.append('    pcol, kcol = _split(W, c8)')
    lines.append('    pat = g[prow[0]:prow[-1] + 1, pcol[0]:pcol[-1] + 1].copy()')
    lines.append('    key = g[krow[0]:krow[-1] + 1, kcol[0]:kcol[-1] + 1]')
    lines.append('    kr = [0, key.shape[0] - 1]')
    lines.append('    kc = [0, key.shape[1] - 1]')
    lines.append('    ph, pw = pat.shape')
    lines.append('    hh, hw = ph // 2, pw // 2')
    lines.append('    out = pat.copy()')
    lines.append('    for r in range(ph):')
    lines.append('        qi = 0 if r < hh else 1')
    lines.append('        for c in range(pw):')
    lines.append('            qj = 0 if c < hw else 1')
    lines.append('            if pat[r, c] == PAT:')
    lines.append('                out[r, c] = int(key[kr[qi], kc[qj]])')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
