def build_program(d4, palette):
    zero = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter, deque')
    lines.append('')
    lines.append('ZERO = %d' % zero)
    lines.append('')
    lines.append('def _components(mask):')
    lines.append('    h, w = mask.shape')
    lines.append('    seen = np.zeros_like(mask, dtype=bool)')
    lines.append('    out = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if mask[y, x] and not seen[y, x]:')
    lines.append('                q = deque([(y, x)])')
    lines.append('                seen[y, x] = True')
    lines.append('                cells = []')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('                out.append(cells)')
    lines.append('    return out')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    bg = int(Counter(g.ravel().tolist()).most_common(1)[0][0])')
    lines.append('    comps = _components(g != bg)')
    lines.append('    boxes = []')
    lines.append('    for cells in comps:')
    lines.append('        if len(cells) <= 1:')
    lines.append('            continue')
    lines.append('        ys = [c[0] for c in cells]')
    lines.append('        xs = [c[1] for c in cells]')
    lines.append('        boxes.append((min(ys), min(xs), max(ys), max(xs)))')
    lines.append('    if not boxes:')
    lines.append('        return [[ZERO]]')
    lines.append('    boxes.sort()')
    lines.append('    sizes = Counter((b[2] - b[0] + 1, b[3] - b[1] + 1) for b in boxes)')
    lines.append('    h, w = sizes.most_common(1)[0][0]')
    lines.append('    out = np.full((h, w), ZERO, dtype=int)')
    lines.append('    for y0, x0, y1, x1 in boxes:')
    lines.append('        sub = g[y0:y1 + 1, x0:x1 + 1]')
    lines.append('        for y in range(min(h, sub.shape[0])):')
    lines.append('            for x in range(min(w, sub.shape[1])):')
    lines.append('                v = int(sub[y, x])')
    lines.append('                if v != bg and v != ZERO:')
    lines.append('                    out[y, x] = v')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
