def build_program(d4, palette):
    target = int(palette[0])
    paint = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('TARGET = ' + repr(target))
    lines.append('PAINT = ' + repr(paint))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    h, w = g.shape')
    lines.append('    for y in range(1, h - 1):')
    lines.append('        for x in range(1, w - 1):')
    lines.append('            cells = [(y, x), (y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)]')
    lines.append('            if all(g[a, b] == TARGET for a, b in cells):')
    lines.append('                for a, b in cells:')
    lines.append('                    out[a, b] = PAINT')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
