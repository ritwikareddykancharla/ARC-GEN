def build_program(d4, palette):
    bg = int(palette[0])
    lines = [
        'import numpy as np',
        '',
        'BG = %d' % bg,
        '',
        'def _block_colour(g, cols):',
        '    best = None',
        '    best_key = None',
        '    for c in cols:',
        '        m = (g == c)',
        '        n = np.zeros_like(m)',
        '        n[1:, :] |= m[:-1, :]',
        '        n[:-1, :] |= m[1:, :]',
        '        n[:, 1:] |= m[:, :-1]',
        '        n[:, :-1] |= m[:, 1:]',
        '        key = (int((m & n).sum()), int(m.sum()))',
        '        if best_key is None or key > best_key:',
        '            best_key = key',
        '            best = c',
        '    return best',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    H, W = g.shape',
        '    cols = [int(v) for v in np.unique(g) if int(v) != BG]',
        '    if not cols:',
        '        return g.tolist()',
        '    block = _block_colour(g, cols)',
        '    noise = (g != BG) & (g != block)',
        '    solid = (g == block)',
        '    pts = [(int(y), int(x)) for y, x in zip(*np.nonzero(noise))]',
        '    def sol(y, x):',
        '        return 0 <= y < H and 0 <= x < W and bool(solid[y, x])',
        '    changed = True',
        '    while changed:',
        '        changed = False',
        '        for (y, x) in pts:',
        '            if solid[y, x]:',
        '                continue',
        '            hit = False',
        '            for dy in (-1, 1):',
        '                for dx in (-1, 1):',
        '                    if sol(y, x + dx) and sol(y + dy, x) and sol(y + dy, x + dx):',
        '                        hit = True',
        '            if hit:',
        '                solid[y, x] = True',
        '                changed = True',
        '    out = g.copy()',
        '    for (y, x) in pts:',
        '        out[y, x] = block if solid[y, x] else BG',
        '    return out.tolist()',
        ''
    ]
    return '\n'.join(lines)
