def build_program(d4, palette):
    side = ('top', 'right', 'bottom', 'left')[int(d4) % 4]
    fill = int(palette[6])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('')
    lines.append('SIDE = %r' % side)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def _background(g):')
    lines.append('    cnt = Counter(g.ravel().tolist())')
    lines.append('    best = max(cnt.values())')
    lines.append('    return int(min(c for c, v in cnt.items() if v == best))')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    bg = _background(g)')
    lines.append('    if SIDE == "top":')
    lines.append('        out = np.full((3, w), bg, dtype=int)')
    lines.append('        k = min(2, h)')
    lines.append('        out[0:k, :] = g[0:k, :]')
    lines.append('        out[2, g[0, :] != bg] = FILL')
    lines.append('    elif SIDE == "bottom":')
    lines.append('        out = np.full((3, w), bg, dtype=int)')
    lines.append('        k = min(2, h)')
    lines.append('        out[3 - k:3, :] = g[h - k:h, :]')
    lines.append('        out[0, g[h - 1, :] != bg] = FILL')
    lines.append('    elif SIDE == "left":')
    lines.append('        out = np.full((h, 3), bg, dtype=int)')
    lines.append('        k = min(2, w)')
    lines.append('        out[:, 0:k] = g[:, 0:k]')
    lines.append('        out[g[:, 0] != bg, 2] = FILL')
    lines.append('    else:')
    lines.append('        out = np.full((h, 3), bg, dtype=int)')
    lines.append('        k = min(2, w)')
    lines.append('        out[:, 3 - k:3] = g[:, w - k:w]')
    lines.append('        out[g[:, w - 1] != bg, 0] = FILL')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
