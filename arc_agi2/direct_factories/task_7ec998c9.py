def build_program(d4, palette):
    k = d4 % 4
    f = 1 if d4 >= 4 else 0
    vertical = (k % 2 == 0)
    parity = (k + f) % 2
    one = int(palette[1])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('ONE = %d' % one)
    lines.append('VERTICAL = %s' % ('True' if vertical else 'False'))
    lines.append('PARITY = %d' % parity)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int).copy()')
    lines.append('    H, W = g.shape')
    lines.append('    bg = int(Counter(g.ravel().tolist()).most_common(1)[0][0])')
    lines.append('    ys, xs = np.where(g != bg)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return g.tolist()')
    lines.append('    sy, sx = int(ys[0]), int(xs[0])')
    lines.append('    seed = int(g[sy, sx])')
    lines.append('    centred = (2 * sy == H - 1) and (2 * sx == W - 1)')
    lines.append('    q = PARITY ^ (1 if centred else 0)')
    lines.append('    if VERTICAL:')
    lines.append('        # stroke runs along the seed column, arms lie on the first and last rows')
    lines.append('        g[:, sx] = ONE')
    lines.append('        if q == 0:')
    lines.append('            g[0, :sx + 1] = ONE')
    lines.append('            g[H - 1, sx:] = ONE')
    lines.append('        else:')
    lines.append('            g[0, sx:] = ONE')
    lines.append('            g[H - 1, :sx + 1] = ONE')
    lines.append('    else:')
    lines.append('        # stroke runs along the seed row, arms lie on the first and last columns')
    lines.append('        g[sy, :] = ONE')
    lines.append('        if q == 0:')
    lines.append('            g[:sy + 1, 0] = ONE')
    lines.append('            g[sy:, W - 1] = ONE')
    lines.append('        else:')
    lines.append('            g[sy:, 0] = ONE')
    lines.append('            g[:sy + 1, W - 1] = ONE')
    lines.append('    g[sy, sx] = seed')
    lines.append('    return g.tolist()')
    return '\n'.join(lines) + '\n'
