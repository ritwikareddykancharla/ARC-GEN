def build_program(d4, palette):
    bg = int(palette[0])
    one = int(palette[5])
    two = int(palette[7])
    lines = []
    lines.append('BG = %d' % bg)
    lines.append('FILL_ONE = %d' % one)
    lines.append('FILL_TWO = %d' % two)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    if H == 0:')
    lines.append('        return g')
    lines.append('    W = len(g[0])')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    seen = [[False] * W for _ in range(H)]')
    lines.append('    for sy in range(H):')
    lines.append('        for sx in range(W):')
    lines.append('            if g[sy][sx] != BG or seen[sy][sx]:')
    lines.append('                continue')
    lines.append('            seen[sy][sx] = True')
    lines.append('            stack = [(sy, sx)]')
    lines.append('            cells = []')
    lines.append('            touches = False')
    lines.append('            while stack:')
    lines.append('                y, x = stack.pop()')
    lines.append('                cells.append((y, x))')
    lines.append('                if y == 0 or x == 0 or y == H - 1 or x == W - 1:')
    lines.append('                    touches = True')
    lines.append('                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                    ny, nx = y + dy, x + dx')
    lines.append('                    if 0 <= ny < H and 0 <= nx < W and not seen[ny][nx] and g[ny][nx] == BG:')
    lines.append('                        seen[ny][nx] = True')
    lines.append('                        stack.append((ny, nx))')
    lines.append('            if touches:')
    lines.append('                continue')
    lines.append('            colour = FILL_ONE if len(cells) == 1 else FILL_TWO')
    lines.append('            for y, x in cells:')
    lines.append('                out[y][x] = colour')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
