def build_program(d4, palette):
    special = int(palette[2])
    bg = int(palette[6])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('SPECIAL = %d' % special)
    lines.append('BG = %d' % bg)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    out = np.full((h, w), BG, dtype=int)')
    lines.append('    ys, xs = np.where(g == SPECIAL)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return out.tolist()')
    lines.append('    y, x = int(ys[0]), int(xs[0])')
    lines.append('    qh = max(1, h // 2)')
    lines.append('    qw = max(1, w // 2)')
    lines.append('    if y < qh:')
    lines.append('        r0, r1 = 0, qh')
    lines.append('    else:')
    lines.append('        r0, r1 = h - qh, h')
    lines.append('    if x < qw:')
    lines.append('        c0, c1 = 0, qw')
    lines.append('    else:')
    lines.append('        c0, c1 = w - qw, w')
    lines.append('    out[r0:r1, c0:c1] = SPECIAL')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
