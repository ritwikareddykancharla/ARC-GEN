def build_program(d4, palette):
    d4 = int(d4) % 8

    def fwd(r, c, H, W):
        if d4 >= 4:
            c = W - 1 - c
        for _ in range(d4 % 4):
            r, c, H, W = c, H - 1 - r, W, H
        return (r, c)

    fill = [fwd(i, j, 3, 3) for i in range(3) for j in range(3)]
    a = fwd(0, 0, 4, 9)
    b = fwd(0, 1, 4, 9)
    kr = b[0] - a[0]
    kc = b[1] - a[1]
    bg = int(palette[0])
    lines = []
    lines.append('from collections import deque')
    lines.append('BG = %d' % bg)
    lines.append('FILL = %r' % (fill,))
    lines.append('KR = %d' % kr)
    lines.append('KC = %d' % kc)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [[int(v) for v in row] for row in grid]')
    lines.append('    H = len(g)')
    lines.append('    W = len(g[0]) if H else 0')
    lines.append('    seen = [[False] * W for _ in range(H)]')
    lines.append('    counts = {}')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y][x] != BG or seen[y][x]:')
    lines.append('                continue')
    lines.append('            seen[y][x] = True')
    lines.append('            q = deque([(y, x)])')
    lines.append('            cells = []')
    lines.append('            touch = False')
    lines.append('            neigh = {}')
    lines.append('            while q:')
    lines.append('                cy, cx = q.popleft()')
    lines.append('                cells.append((cy, cx))')
    lines.append('                if cy == 0 or cx == 0 or cy == H - 1 or cx == W - 1:')
    lines.append('                    touch = True')
    lines.append('                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                    ny, nx = cy + dy, cx + dx')
    lines.append('                    if 0 <= ny < H and 0 <= nx < W:')
    lines.append('                        v = g[ny][nx]')
    lines.append('                        if v == BG:')
    lines.append('                            if not seen[ny][nx]:')
    lines.append('                                seen[ny][nx] = True')
    lines.append('                                q.append((ny, nx))')
    lines.append('                        else:')
    lines.append('                            neigh[v] = neigh.get(v, 0) + 1')
    lines.append('            if touch or not neigh:')
    lines.append('                continue')
    lines.append('            col = max(neigh, key=lambda k: (neigh[k], -k))')
    lines.append('            counts[col] = counts.get(col, 0) + len(cells)')
    lines.append('    keys = {}')
    lines.append('    for c in counts:')
    lines.append('        best = None')
    lines.append('        for y in range(H):')
    lines.append('            for x in range(W):')
    lines.append('                if g[y][x] == c:')
    lines.append('                    k = KR * y + KC * x')
    lines.append('                    if best is None or k < best:')
    lines.append('                        best = k')
    lines.append('        keys[c] = best if best is not None else 0')
    lines.append('    out = [[BG] * 3 for _ in range(3)]')
    lines.append('    line = 0')
    lines.append('    for c in sorted(counts, key=lambda c: (keys[c], c)):')
    lines.append('        n = counts[c]')
    lines.append('        pos = line * 3')
    lines.append('        for i in range(n):')
    lines.append('            if pos + i < 9:')
    lines.append('                r, cc = FILL[pos + i]')
    lines.append('                out[r][cc] = c')
    lines.append('        line += (n + 2) // 3')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
