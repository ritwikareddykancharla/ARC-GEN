def build_program(d4, palette):
    bg = int(palette[0])
    red = int(palette[2])
    lines = [
        'import numpy as np',
        'from collections import deque',
        '',
        'BG = ' + str(bg),
        'RED = ' + str(red),
        '',
        'def _components(mask):',
        '    h, w = mask.shape',
        '    seen = np.zeros((h, w), dtype=bool)',
        '    comps = []',
        '    for y in range(h):',
        '        for x in range(w):',
        '            if mask[y, x] and not seen[y, x]:',
        '                seen[y, x] = True',
        '                q = deque([(y, x)])',
        '                cells = []',
        '                while q:',
        '                    cy, cx = q.popleft()',
        '                    cells.append((cy, cx))',
        '                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):',
        '                        ny, nx = cy + dy, cx + dx',
        '                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:',
        '                            seen[ny, nx] = True',
        '                            q.append((ny, nx))',
        '                comps.append(cells)',
        '    return comps',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.asarray(grid, dtype=int)',
        '    comps = _components(g != BG)',
        '    if not comps:',
        '        return [row[:] for row in np.asarray(grid).tolist()]',
        '    best = None',
        '    best_count = -1',
        '    for cells in comps:',
        '        cnt = 0',
        '        for (y, x) in cells:',
        '            if g[y, x] == RED:',
        '                cnt += 1',
        '        if cnt > best_count:',
        '            best_count = cnt',
        '            best = cells',
        '    ys = [c[0] for c in best]',
        '    xs = [c[1] for c in best]',
        '    y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)',
        '    out = g[y0:y1 + 1, x0:x1 + 1]',
        '    return [[int(v) for v in row] for row in out]',
        ''
    ]
    return '\n'.join(lines)
