def build_program(d4, palette):
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('')
    lines.append('def _band_starts_rows(c):')
    lines.append('    H = c.shape[0]')
    lines.append('    starts = [0]')
    lines.append('    for y in range(1, H):')
    lines.append('        if not np.array_equal(c[y], c[y - 1]):')
    lines.append('            starts.append(y)')
    lines.append('    return starts')
    lines.append('')
    lines.append('def _band_starts_cols(c):')
    lines.append('    W = c.shape[1]')
    lines.append('    starts = [0]')
    lines.append('    for x in range(1, W):')
    lines.append('        if not np.array_equal(c[:, x], c[:, x - 1]):')
    lines.append('            starts.append(x)')
    lines.append('    return starts')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    ys, xs = np.where(g != BG)')
    lines.append('    if ys.size == 0:')
    lines.append('        return [[BG]]')
    lines.append('    c = g[ys.min():ys.max() + 1, xs.min():xs.max() + 1]')
    lines.append('    rstarts = _band_starts_rows(c)')
    lines.append('    cstarts = _band_starts_cols(c)')
    lines.append('    out = [[int(c[y, x]) for x in cstarts] for y in rstarts]')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
