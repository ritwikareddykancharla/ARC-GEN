def build_program(d4, palette):
    pal = [int(p) for p in palette]
    bg = pal[0]
    ring = {pal[3]: pal[6], pal[8]: pal[4], pal[2]: pal[1]}
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('RING = %r' % (ring,))
    lines.append('')
    lines.append('def _learn(demonstrations):')
    lines.append('    table = dict(RING)')
    lines.append('    for pair in demonstrations or []:')
    lines.append('        try:')
    lines.append('            gi = np.asarray(pair["input"], dtype=int)')
    lines.append('            go = np.asarray(pair["output"], dtype=int)')
    lines.append('        except Exception:')
    lines.append('            continue')
    lines.append('        if gi.shape != go.shape or gi.ndim != 2:')
    lines.append('            continue')
    lines.append('        H, W = gi.shape')
    lines.append('        for y in range(H):')
    lines.append('            for x in range(W):')
    lines.append('                c = int(gi[y, x])')
    lines.append('                if c == BG or c in table:')
    lines.append('                    continue')
    lines.append('                for dy in (-1, 0, 1):')
    lines.append('                    for dx in (-1, 0, 1):')
    lines.append('                        if dy == 0 and dx == 0:')
    lines.append('                            continue')
    lines.append('                        yy, xx = y + dy, x + dx')
    lines.append('                        if 0 <= yy < H and 0 <= xx < W and int(gi[yy, xx]) == BG and int(go[yy, xx]) != BG:')
    lines.append('                            table.setdefault(c, int(go[yy, xx]))')
    lines.append('    return table')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.asarray(grid, dtype=int)')
    lines.append('    table = _learn(demonstrations)')
    lines.append('    out = g.copy()')
    lines.append('    H, W = g.shape')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            c = int(g[y, x])')
    lines.append('            if c == BG or c not in table:')
    lines.append('                continue')
    lines.append('            rc = table[c]')
    lines.append('            for dy in (-1, 0, 1):')
    lines.append('                for dx in (-1, 0, 1):')
    lines.append('                    if dy == 0 and dx == 0:')
    lines.append('                        continue')
    lines.append('                    yy, xx = y + dy, x + dx')
    lines.append('                    if 0 <= yy < H and 0 <= xx < W and out[yy, xx] == BG:')
    lines.append('                        out[yy, xx] = rc')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
