def build_program(d4, palette):
    grey = int(palette[5])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('GREY = %d' % grey)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.asarray(grid, dtype=int)')
    lines.append('    vals, counts = np.unique(g, return_counts=True)')
    lines.append('    top = counts.max()')
    lines.append('    winners = [int(v) for v, c in zip(vals.tolist(), counts.tolist()) if c == top]')
    lines.append('    if len(winners) != 1:')
    lines.append('        raise ValueError("No unique most frequent colour; outside the constructor domain")')
    lines.append('    mode = winners[0]')
    lines.append('    out = np.where(g == mode, g, GREY)')
    lines.append('    return out.astype(int).tolist()')
    lines.append('')
    return '\n'.join(lines)
