def build_program(d4, palette):
    bg = int(palette[0])
    div = int(palette[4])
    mark = int(palette[3])
    # Original panels are stacked vertically (rows). Odd number of quarter turns
    # makes them side-by-side (columns); row reversal does not change the axis.
    horizontal = (d4 % 4) % 2 == 1
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DIV = %d' % div)
    lines.append('MARK = %d' % mark)
    lines.append('SIDE_BY_SIDE = %s' % ('True' if horizontal else 'False'))
    lines.append('')
    lines.append('def _split_rows(g):')
    lines.append('    h = g.shape[0]')
    lines.append('    k = None')
    lines.append('    for y in range(h):')
    lines.append('        if (g[y] == DIV).all():')
    lines.append('            k = y')
    lines.append('            break')
    lines.append('    if k is None:')
    lines.append('        k = h // 2')
    lines.append('        return g[:k], g[h - k:]')
    lines.append('    return g[:k], g[k + 1:]')
    lines.append('')
    lines.append('def _split_cols(g):')
    lines.append('    w = g.shape[1]')
    lines.append('    k = None')
    lines.append('    for x in range(w):')
    lines.append('        if (g[:, x] == DIV).all():')
    lines.append('            k = x')
    lines.append('            break')
    lines.append('    if k is None:')
    lines.append('        k = w // 2')
    lines.append('        return g[:, :k], g[:, w - k:]')
    lines.append('    return g[:, :k], g[:, k + 1:]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    side = SIDE_BY_SIDE')
    lines.append('    # Robustness: if the divider line is clearly on the other axis, follow the pixels.')
    lines.append('    if side and g.shape[1] <= g.shape[0] and any((g[y] == DIV).all() for y in range(g.shape[0])):')
    lines.append('        side = False')
    lines.append('    elif (not side) and g.shape[0] <= g.shape[1] and any((g[:, x] == DIV).all() for x in range(g.shape[1])):')
    lines.append('        side = True')
    lines.append('    if side:')
    lines.append('        a, b = _split_cols(g)')
    lines.append('    else:')
    lines.append('        a, b = _split_rows(g)')
    lines.append('    hh = min(a.shape[0], b.shape[0])')
    lines.append('    ww = min(a.shape[1], b.shape[1])')
    lines.append('    a = a[:hh, :ww]')
    lines.append('    b = b[:hh, :ww]')
    lines.append('    x = (a != BG) ^ (b != BG)')
    lines.append('    out = np.where(x, MARK, BG).astype(int)')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
