def build_program(d4, palette):
    bg = int(palette[0])
    seed = int(palette[1])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('SEED = %d' % seed)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    if g.ndim != 2:')
    lines.append('        return [list(r) for r in grid]')
    lines.append('    H, W = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    q = deque()')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y, x] == SEED:')
    lines.append('                q.append((y, x))')
    lines.append('    while q:')
    lines.append('        y, x = q.popleft()')
    lines.append('        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('            ny, nx = y + dy, x + dx')
    lines.append('            if 0 <= ny < H and 0 <= nx < W and out[ny, nx] == BG:')
    lines.append('                out[ny, nx] = SEED')
    lines.append('                q.append((ny, nx))')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
