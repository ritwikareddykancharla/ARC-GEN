def build_program(d4, palette):
    bg = int(palette[0])
    red = int(palette[2])
    green = int(palette[3])
    fill = int(palette[8])
    swap = (int(d4) % 4) % 2 == 1
    lines = []
    lines.append('BG = %d' % bg)
    lines.append('RED = %d' % red)
    lines.append('GREEN = %d' % green)
    lines.append('FILL = %d' % fill)
    lines.append('CORNER_GREEN_ROW_RED_COL = %s' % ('True' if swap else 'False'))
    lines.append('')
    lines.append('def _find(g, colour):')
    lines.append('    for r, row in enumerate(g):')
    lines.append('        for c, v in enumerate(row):')
    lines.append('            if v == colour:')
    lines.append('                return (r, c)')
    lines.append('    return None')
    lines.append('')
    lines.append('def _seg(a, b):')
    lines.append('    # cells on the straight segment from a to b, excluding a, including b')
    lines.append('    cells = []')
    lines.append('    r, c = a')
    lines.append('    br, bc = b')
    lines.append('    dr = (br > r) - (br < r)')
    lines.append('    dc = (bc > c) - (bc < c)')
    lines.append('    while (r, c) != (br, bc):')
    lines.append('        if r != br:')
    lines.append('            r += dr')
    lines.append('        else:')
    lines.append('            c += dc')
    lines.append('        cells.append((r, c))')
    lines.append('    return cells')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(row) for row in grid]')
    lines.append('    rp = _find(g, RED)')
    lines.append('    gp = _find(g, GREEN)')
    lines.append('    if rp is None or gp is None:')
    lines.append('        return g')
    lines.append('    if CORNER_GREEN_ROW_RED_COL:')
    lines.append('        corner = (gp[0], rp[1])')
    lines.append('    else:')
    lines.append('        corner = (rp[0], gp[1])')
    lines.append('    path = _seg(rp, corner)')
    lines.append('    second = _seg(corner, gp)')
    lines.append('    path += second[:-1]')
    lines.append('    for (r, c) in path:')
    lines.append('        if g[r][c] == BG:')
    lines.append('            g[r][c] = FILL')
    lines.append('    return g')
    return '\n'.join(lines) + '\n'
