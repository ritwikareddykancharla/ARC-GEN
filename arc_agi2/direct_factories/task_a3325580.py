def build_program(d4, palette):
    d4 = int(d4) % 8
    # Original x-axis (left->right ordering, output column index) stays horizontal
    # for 0/180-degree rotations (with or without a row flip) and becomes vertical
    # for 90/270-degree rotations. The same transform is applied to the output, so
    # in visible coordinates the output order matches the visible order of the
    # objects along that axis (ascending), whatever the direction of the original axis.
    horizontal = (d4 % 4) in (0, 2)
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('HORIZONTAL = %s' % ('True' if horizontal else 'False'))
    lines.append('')
    lines.append('def _objects(g):')
    lines.append('    h, w = g.shape')
    lines.append('    seen = np.zeros((h, w), dtype=bool)')
    lines.append('    objs = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if seen[y, x] or int(g[y, x]) == BG:')
    lines.append('                continue')
    lines.append('            col = int(g[y, x])')
    lines.append('            seen[y, x] = True')
    lines.append('            q = deque([(y, x)])')
    lines.append('            cells = []')
    lines.append('            while q:')
    lines.append('                cy, cx = q.popleft()')
    lines.append('                cells.append((cy, cx))')
    lines.append('                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                    ny, nx = cy + dy, cx + dx')
    lines.append('                    if 0 <= ny < h and 0 <= nx < w and not seen[ny, nx] and int(g[ny, nx]) == col:')
    lines.append('                        seen[ny, nx] = True')
    lines.append('                        q.append((ny, nx))')
    lines.append('            ys = [c[0] for c in cells]')
    lines.append('            xs = [c[1] for c in cells]')
    lines.append('            objs.append({"colour": col, "size": len(cells), "top": min(ys), "left": min(xs)})')
    lines.append('    return objs')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.asarray(grid, dtype=int)')
    lines.append('    objs = _objects(g)')
    lines.append('    if not objs:')
    lines.append('        return [[BG]]')
    lines.append('    n = max(o["size"] for o in objs)')
    lines.append('    big = [o for o in objs if o["size"] == n]')
    lines.append('    if HORIZONTAL:')
    lines.append('        big.sort(key=lambda o: (o["left"], o["top"]))')
    lines.append('        return [[o["colour"] for o in big] for _ in range(n)]')
    lines.append('    else:')
    lines.append('        big.sort(key=lambda o: (o["top"], o["left"]))')
    lines.append('        return [[o["colour"]] * n for o in big]')
    return '\n'.join(lines) + '\n'
