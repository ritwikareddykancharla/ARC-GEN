def build_program(d4, palette):
    bg = int(palette[0])
    gray = int(palette[5])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('GRAY = %d' % gray)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = np.full((9, 9), GRAY, dtype=int)')
    lines.append('    claimed = np.zeros((H, W), dtype=bool)')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y, x] == BG or claimed[y, x]:')
    lines.append('                continue')
    lines.append('            # first unclaimed non-background cell in reading order is a tile top-left corner')
    lines.append('            y1 = min(y + 3, H)')
    lines.append('            x1 = min(x + 3, W)')
    lines.append('            claimed[y:y1, x:x1] = True')
    lines.append('            tile = g[y:y + 3, x:x + 3].copy()')
    lines.append('            if tile.shape != (3, 3):')
    lines.append('                continue')
    lines.append('            ys, xs = np.nonzero(tile != GRAY)')
    lines.append('            if len(ys) == 0:')
    lines.append('                sy, sx = 0, 0')
    lines.append('            else:')
    lines.append('                sy = int(np.sign(ys.mean() - 1.0))')
    lines.append('                sx = int(np.sign(xs.mean() - 1.0))')
    lines.append('            r = (sy + 1) * 3')
    lines.append('            c = (sx + 1) * 3')
    lines.append('            out[r:r + 3, c:c + 3] = tile')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
