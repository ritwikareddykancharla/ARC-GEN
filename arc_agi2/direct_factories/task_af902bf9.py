def build_program(d4, palette):
    bg = int(palette[0])
    corner = int(palette[4])
    fill = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('CORNER = %d' % corner)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int).copy()')
    lines.append('    H, W = g.shape')
    lines.append('    pts = [(int(r), int(c)) for r, c in zip(*np.nonzero(g != BG))]')
    lines.append('    ptset = set(pts)')
    lines.append('    rects = []')
    lines.append('    for (r0, c0) in sorted(pts):')
    lines.append('        for (r1, c1) in sorted(pts):')
    lines.append('            if r1 - r0 < 2 or c1 - c0 < 2:')
    lines.append('                continue')
    lines.append('            if (r0, c1) not in ptset or (r1, c0) not in ptset:')
    lines.append('                continue')
    lines.append('            blocked = False')
    lines.append('            for (pr, pc) in pts:')
    lines.append('                if r0 < pr < r1 and c0 < pc < c1:')
    lines.append('                    blocked = True')
    lines.append('                    break')
    lines.append('            if blocked:')
    lines.append('                continue')
    lines.append('            rects.append((r0, c0, r1, c1))')
    lines.append('    for (r0, c0, r1, c1) in rects:')
    lines.append('        g[r0 + 1:r1, c0 + 1:c1] = FILL')
    lines.append('    return g.tolist()')
    lines.append('')
    return '\n'.join(lines)
