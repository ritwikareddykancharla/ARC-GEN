def build_program(d4, palette):
    Z = int(palette[0])
    F = int(palette[7])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('BOX = %d' % Z)
    lines.append('FILL = %d' % F)
    lines.append('')
    lines.append('def _components(mask):')
    lines.append('    H, W = mask.shape')
    lines.append('    seen = np.zeros_like(mask, dtype=bool)')
    lines.append('    comps = []')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if mask[y, x] and not seen[y, x]:')
    lines.append('                q = deque([(y, x)])')
    lines.append('                seen[y, x] = True')
    lines.append('                cells = []')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < H and 0 <= nx < W and mask[ny, nx] and not seen[ny, nx]:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('                comps.append(cells)')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    plans = []')
    lines.append('    for cells in _components(g == BOX):')
    lines.append('        ys = [c[0] for c in cells]')
    lines.append('        xs = [c[1] for c in cells]')
    lines.append('        y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)')
    lines.append('        h, w = y1 - y0 + 1, x1 - x0 + 1')
    lines.append('        if x0 == 0:')
    lines.append('            plans.append(((y0, 0, y1, W - 1), (y0, W - w, y1, W - 1)))')
    lines.append('        elif x1 == W - 1:')
    lines.append('            plans.append(((y0, 0, y1, W - 1), (y0, 0, y1, w - 1)))')
    lines.append('        elif y0 == 0:')
    lines.append('            plans.append(((0, x0, H - 1, x1), (H - h, x0, H - 1, x1)))')
    lines.append('        elif y1 == H - 1:')
    lines.append('            plans.append(((0, x0, H - 1, x1), (0, x0, h - 1, x1)))')
    lines.append('    for sweep, dest in plans:')
    lines.append('        a, b, c, d = sweep')
    lines.append('        out[a:c + 1, b:d + 1] = FILL')
    lines.append('    for sweep, dest in plans:')
    lines.append('        a, b, c, d = dest')
    lines.append('        out[a:c + 1, b:d + 1] = BOX')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
