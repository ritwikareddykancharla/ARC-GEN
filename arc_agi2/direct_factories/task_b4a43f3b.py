def build_program(d4, palette):
    d4 = int(d4) % 8
    k = d4 % 4
    bg = int(palette[0])
    div = int(palette[5])
    # Original layout: motif block on top (rows 0-5), divider row of 5s, placement map below.
    # A horizontal flip (d4>=4) keeps top on top. Each clockwise turn moves top -> right -> bottom -> left.
    horizontal = (k % 2 == 0)
    motif_first = (k == 0 or k == 3)  # top (k=0) or left (k=3) comes before the divider
    src = []
    src.append('import numpy as np')
    src.append('')
    src.append('BG = %d' % bg)
    src.append('DIV = %d' % div)
    src.append('HORIZONTAL = %r' % horizontal)
    src.append('MOTIF_FIRST = %r' % motif_first)
    src.append('MOTIF_N = 3')
    src.append('')
    src.append('def _find_divider(g, horizontal):')
    src.append('    H, W = g.shape')
    src.append('    n = H if horizontal else W')
    src.append('    L = W if horizontal else H')
    src.append('    total = int(np.sum(g == DIV))')
    src.append('    cands = []')
    src.append('    for i in range(n):')
    src.append('        line = g[i, :] if horizontal else g[:, i]')
    src.append('        if np.all(line == DIV):')
    src.append('            cands.append(i)')
    src.append('    for i in cands:')
    src.append('        if total == L:')
    src.append('            return i')
    src.append('    if cands:')
    src.append('        return cands[0]')
    src.append('    for i in range(n):')
    src.append('        line = g[i, :] if horizontal else g[:, i]')
    src.append('        if len(set(line.tolist())) == 1 and int(line[0]) != BG:')
    src.append('            return i')
    src.append('    return n // 2')
    src.append('')
    src.append('def solve(demonstrations, grid):')
    src.append('    g = np.array(grid, dtype=int)')
    src.append('    d = _find_divider(g, HORIZONTAL)')
    src.append('    if HORIZONTAL:')
    src.append('        before, after = g[:d, :], g[d + 1:, :]')
    src.append('    else:')
    src.append('        before, after = g[:, :d], g[:, d + 1:]')
    src.append('    if MOTIF_FIRST:')
    src.append('        mreg, pat = before, after')
    src.append('    else:')
    src.append('        mreg, pat = after, before')
    src.append('    fh = max(1, mreg.shape[0] // MOTIF_N)')
    src.append('    fw = max(1, mreg.shape[1] // MOTIF_N)')
    src.append('    motif = mreg[::fh, ::fw][:MOTIF_N, :MOTIF_N]')
    src.append('    mh, mw = motif.shape')
    src.append('    ph, pw = pat.shape')
    src.append('    out = np.full((ph * mh, pw * mw), BG, dtype=int)')
    src.append('    for i in range(ph):')
    src.append('        for j in range(pw):')
    src.append('            if int(pat[i, j]) != BG:')
    src.append('                out[i * mh:(i + 1) * mh, j * mw:(j + 1) * mw] = motif')
    src.append('    return out.tolist()')
    return '\n'.join(src) + '\n'
