def build_program(d4, palette):
    gray = int(palette[5])
    blue = int(palette[1])
    yellow = int(palette[4])
    red = int(palette[2])
    lines = []
    lines.append('GRAY = %d' % gray)
    lines.append('CORNER = %d' % blue)
    lines.append('EDGE = %d' % yellow)
    lines.append('INTERIOR = %d' % red)
    lines.append('')
    lines.append('def _components(grid, colour):')
    lines.append('    h = len(grid)')
    lines.append('    w = len(grid[0]) if h else 0')
    lines.append('    seen = [[False] * w for _ in range(h)]')
    lines.append('    comps = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if grid[y][x] == colour and not seen[y][x]:')
    lines.append('                seen[y][x] = True')
    lines.append('                stack = [(y, x)]')
    lines.append('                cells = []')
    lines.append('                while stack:')
    lines.append('                    cy, cx = stack.pop()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and not seen[ny][nx] and grid[ny][nx] == colour:')
    lines.append('                            seen[ny][nx] = True')
    lines.append('                            stack.append((ny, nx))')
    lines.append('                comps.append(cells)')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [[int(v) for v in row] for row in grid]')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    for cells in _components(g, GRAY):')
    lines.append('        ys = [c[0] for c in cells]')
    lines.append('        xs = [c[1] for c in cells]')
    lines.append('        y0, y1, x0, x1 = min(ys), max(ys), min(xs), max(xs)')
    lines.append('        for y, x in cells:')
    lines.append('            on_y = y == y0 or y == y1')
    lines.append('            on_x = x == x0 or x == x1')
    lines.append('            if on_y and on_x:')
    lines.append('                out[y][x] = CORNER')
    lines.append('            elif on_y or on_x:')
    lines.append('                out[y][x] = EDGE')
    lines.append('            else:')
    lines.append('                out[y][x] = INTERIOR')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
