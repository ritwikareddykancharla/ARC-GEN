def build_program(d4, palette):
    d4 = int(d4) % 8
    horizontal = d4 in (0, 2, 4, 6)
    if horizontal:
        from_start = d4 in (0, 6)
    else:
        from_start = d4 in (1, 7)
    fg = int(palette[4])
    mark = int(palette[6])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('HORIZONTAL = ' + repr(bool(horizontal)))
    lines.append('FROM_START = ' + repr(bool(from_start)))
    lines.append('FG = ' + repr(fg))
    lines.append('MARK = ' + repr(mark))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    h, w = g.shape')
    lines.append('    if HORIZONTAL:')
    lines.append('        mid = h // 2')
    lines.append('        for i in range(0, w, 3):')
    lines.append('            x = i if FROM_START else w - 1 - i')
    lines.append('            out[mid, x] = MARK')
    lines.append('            for y in range(h):')
    lines.append('                if y != mid and g[y, x] == FG:')
    lines.append('                    out[y, x] = MARK')
    lines.append('    else:')
    lines.append('        mid = w // 2')
    lines.append('        for i in range(0, h, 3):')
    lines.append('            y = i if FROM_START else h - 1 - i')
    lines.append('            out[y, mid] = MARK')
    lines.append('            for x in range(w):')
    lines.append('                if x != mid and g[y, x] == FG:')
    lines.append('                    out[y, x] = MARK')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
