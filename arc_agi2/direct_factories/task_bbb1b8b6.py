def build_program(d4, palette):
    d4 = int(d4) % 8
    horizontal = (d4 % 2 == 0)
    base_first = d4 in (0, 1, 6, 7)
    bg = int(palette[0])
    div = int(palette[5])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('HORIZ = ' + repr(bool(horizontal)))
    lines.append('BASE_FIRST = ' + repr(bool(base_first)))
    lines.append('BG = ' + repr(bg))
    lines.append('DIV = ' + repr(div))
    lines.append('')
    lines.append('def _line(g, i):')
    lines.append('    return g[:, i] if HORIZ else g[i, :]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    n = w if HORIZ else h')
    lines.append('    cands = [i for i in range(n) if np.all(_line(g, i) == DIV)]')
    lines.append('    if not cands:')
    lines.append('        L = h if HORIZ else w')
    lines.append('        for i in range(n):')
    lines.append('            ln = _line(g, i)')
    lines.append('            c = int(ln[0])')
    lines.append('            if c != BG and np.all(ln == c) and int((g == c).sum()) == L:')
    lines.append('                cands.append(i)')
    lines.append('    if not cands:')
    lines.append('        cands = [n // 2]')
    lines.append('    mid = (n - 1) / 2.0')
    lines.append('    d = min(cands, key=lambda i: (abs(i - mid), i))')
    lines.append('    if HORIZ:')
    lines.append('        a = g[:, :d]')
    lines.append('        b = g[:, d + 1:]')
    lines.append('    else:')
    lines.append('        a = g[:d, :]')
    lines.append('        b = g[d + 1:, :]')
    lines.append('    if BASE_FIRST:')
    lines.append('        base, other = a, b')
    lines.append('    else:')
    lines.append('        base, other = b, a')
    lines.append('    out = base.copy()')
    lines.append('    if base.size > 0 and base.shape == other.shape:')
    lines.append('        base_on = base != BG')
    lines.append('        other_on = other != BG')
    lines.append('        if other_on.any() and np.all(base_on != other_on):')
    lines.append('            out = np.where(other_on, other, base)')
    lines.append('    return out.astype(int).tolist()')
    return '\n'.join(lines) + '\n'
