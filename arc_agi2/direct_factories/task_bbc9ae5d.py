def build_program(d4, palette):
    d4 = int(d4) % 8
    bg = int(palette[0])
    vertical = (d4 % 2 == 1)
    far = d4 in (2, 3, 4, 5)
    rev = d4 in (1, 2, 5, 6)
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = ' + repr(bg))
    lines.append('VERTICAL = ' + repr(vertical))
    lines.append('FAR_ANCHOR = ' + repr(far))
    lines.append('STACK_REVERSED = ' + repr(rev))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    if VERTICAL:')
    lines.append('        line = [int(v) for v in g[:, 0]]')
    lines.append('    else:')
    lines.append('        line = [int(v) for v in g[0, :]]')
    lines.append('    W = len(line)')
    lines.append('    if FAR_ANCHOR:')
    lines.append('        anchor = W - 1')
    lines.append('        step = -1')
    lines.append('    else:')
    lines.append('        anchor = 0')
    lines.append('        step = 1')
    lines.append('    fg = line[anchor]')
    lines.append('    k = 0')
    lines.append('    idx = anchor')
    lines.append('    while 0 <= idx < W and line[idx] == fg and fg != BG:')
    lines.append('        k += 1')
    lines.append('        idx += step')
    lines.append('    H = max(1, W // 2)')
    lines.append('    if VERTICAL:')
    lines.append('        out = np.full((W, H), BG, dtype=int)')
    lines.append('    else:')
    lines.append('        out = np.full((H, W), BG, dtype=int)')
    lines.append('    for t in range(H):')
    lines.append('        p = (H - 1 - t) if STACK_REVERSED else t')
    lines.append('        if t == 0:')
    lines.append('            for i in range(W):')
    lines.append('                if VERTICAL:')
    lines.append('                    out[i, p] = line[i]')
    lines.append('                else:')
    lines.append('                    out[p, i] = line[i]')
    lines.append('            continue')
    lines.append('        L = min(W, k + t) if k > 0 else 0')
    lines.append('        for s in range(L):')
    lines.append('            i = anchor + step * s')
    lines.append('            if VERTICAL:')
    lines.append('                out[i, p] = fg')
    lines.append('            else:')
    lines.append('                out[p, i] = fg')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
