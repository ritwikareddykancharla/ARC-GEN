def build_program(d4, palette):
    bg = int(palette[7])
    # Rotations keep the clockwise corner cycle clockwise.
    # Reflections (indices >= 4) reverse it to counter-clockwise.
    step = 1 if (d4 % 8) < 4 else 3
    lines = []
    lines.append('BG = %d' % bg)
    lines.append('STEP = %d  # corner-cycle step over visible corners TL, TR, BR, BL (1 = clockwise, 3 = counter-clockwise)' % step)
    lines.append('')
    lines.append('def _component(g, r, c):')
    lines.append('    H, W = len(g), len(g[0])')
    lines.append('    col = g[r][c]')
    lines.append('    seen = {(r, c)}')
    lines.append('    stack = [(r, c)]')
    lines.append('    while stack:')
    lines.append('        y, x = stack.pop()')
    lines.append('        for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):')
    lines.append('            if 0 <= ny < H and 0 <= nx < W and (ny, nx) not in seen and g[ny][nx] == col:')
    lines.append('                seen.add((ny, nx))')
    lines.append('                stack.append((ny, nx))')
    lines.append('    return seen')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = [list(map(int, row)) for row in grid]')
    lines.append('    H, W = len(g), len(g[0])')
    lines.append('    out = [row[:] for row in g]')
    lines.append('    corners = [(0, 0), (0, W - 1), (H - 1, W - 1), (H - 1, 0)]')
    lines.append('    for i, (cr, cc) in enumerate(corners):')
    lines.append('        col = g[cr][cc]')
    lines.append('        if col == BG:')
    lines.append('            continue')
    lines.append('        comp = _component(g, cr, cc)')
    lines.append('        r0 = min(r for r, _ in comp)')
    lines.append('        c0 = min(c for _, c in comp)')
    lines.append('        h = max(r for r, _ in comp) - r0 + 1')
    lines.append('        w = max(c for _, c in comp) - c0 + 1')
    lines.append('        j = (i + STEP) % 4')
    lines.append('        nr0 = 0 if j in (0, 1) else H - h')
    lines.append('        nc0 = 0 if j in (0, 3) else W - w')
    lines.append('        for r, c in comp:')
    lines.append('            out[nr0 + r - r0][nc0 + c - c0] = col')
    lines.append('    return out')
    return '\n'.join(lines) + '\n'
