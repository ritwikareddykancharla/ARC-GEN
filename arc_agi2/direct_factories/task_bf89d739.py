def build_program(d4, palette):
    bg = int(palette[0])
    dot = int(palette[2])
    fill = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DOT = %d' % dot)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def _paint(out, src, cells):')
    lines.append('    for (r, c) in cells:')
    lines.append('        if src[r, c] == BG:')
    lines.append('            out[r, c] = FILL')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    pts = [(int(r), int(c)) for r, c in zip(*np.nonzero(g == DOT))]')
    lines.append('    if len(pts) < 2:')
    lines.append('        return out.tolist()')
    lines.append('    by_row = {}')
    lines.append('    by_col = {}')
    lines.append('    for r, c in pts:')
    lines.append('        by_row.setdefault(r, []).append(c)')
    lines.append('        by_col.setdefault(c, []).append(r)')
    lines.append('    rcand = sorted(r for r, v in by_row.items() if len(v) >= 2)')
    lines.append('    ccand = sorted(c for c, v in by_col.items() if len(v) >= 2)')
    lines.append('    if rcand and (not ccand or len(rcand) <= len(ccand)):')
    lines.append('        horizontal = True')
    lines.append('    elif ccand:')
    lines.append('        horizontal = False')
    lines.append('    else:')
    lines.append('        return out.tolist()')
    lines.append('    if horizontal:')
    lines.append('        line = rcand[0]')
    lines.append('        cs = sorted(by_row[line])')
    lines.append('        lo, hi = cs[0], cs[-1]')
    lines.append('        _paint(out, g, [(line, c) for c in range(lo + 1, hi)])')
    lines.append('        for r, c in pts:')
    lines.append('            if r == line:')
    lines.append('                continue')
    lines.append('            a, b = sorted((r, line))')
    lines.append('            _paint(out, g, [(rr, c) for rr in range(a + 1, b)])')
    lines.append('    else:')
    lines.append('        line = ccand[0]')
    lines.append('        rs = sorted(by_col[line])')
    lines.append('        lo, hi = rs[0], rs[-1]')
    lines.append('        _paint(out, g, [(r, line) for r in range(lo + 1, hi)])')
    lines.append('        for r, c in pts:')
    lines.append('            if c == line:')
    lines.append('                continue')
    lines.append('            a, b = sorted((c, line))')
    lines.append('            _paint(out, g, [(r, cc) for cc in range(a + 1, b)])')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
