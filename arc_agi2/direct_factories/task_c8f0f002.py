def build_program(d4, palette):
    src = int(palette[7])
    dst = int(palette[5])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('SRC = %d' % src)
    lines.append('DST = %d' % dst)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int).copy()')
    lines.append('    if g.ndim != 2:')
    lines.append('        return [list(r) for r in grid]')
    lines.append('    for r in range(g.shape[0]):')
    lines.append('        row = g[r]')
    lines.append('        mask = row == SRC')
    lines.append('        if mask.any():')
    lines.append('            row[mask] = DST')
    lines.append('    return g.tolist()')
    lines.append('')
    return '\n'.join(lines)
