def build_program(d4, palette):
    a = int(palette[5])
    b = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('COLOR_A = %d' % a)
    lines.append('COLOR_B = %d' % b)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    if COLOR_A == COLOR_B:')
    lines.append('        return out.tolist()')
    lines.append('    mask_a = g == COLOR_A')
    lines.append('    mask_b = g == COLOR_B')
    lines.append('    out[mask_a] = COLOR_B')
    lines.append('    out[mask_b] = COLOR_A')
    lines.append('    return out.tolist()')
    lines.append('')
    return '\n'.join(lines)
