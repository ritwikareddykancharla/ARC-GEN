def build_program(d4, palette):
    bg = int(palette[0])
    lines = [
        'import numpy as np',
        '',
        'BG = ' + str(bg),
        '',
        'def _side(vals):',
        '    vals = [int(v) for v in vals if int(v) != BG]',
        '    if not vals:',
        '        return None',
        '    counts = {}',
        '    for v in vals:',
        '        counts[v] = counts.get(v, 0) + 1',
        '    best = None',
        '    for k in sorted(counts):',
        '        if best is None or counts[k] > counts[best]:',
        '            best = k',
        '    return best',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    H, W = g.shape',
        '    out = g.copy()',
        '    if H < 3 or W < 3:',
        '        return out.tolist()',
        '    top = _side(g[0, 1:W - 1])',
        '    bottom = _side(g[H - 1, 1:W - 1])',
        '    left = _side(g[1:H - 1, 0])',
        '    right = _side(g[1:H - 1, W - 1])',
        '    out[1:H - 1, 1:W - 1] = BG',
        '    for y in range(1, H - 1):',
        '        for x in range(1, W - 1):',
        '            c = int(g[y, x])',
        '            if c == BG:',
        '                continue',
        '            if top is not None and c == top:',
        '                out[1, x] = c',
        '            elif bottom is not None and c == bottom:',
        '                out[H - 2, x] = c',
        '            elif left is not None and c == left:',
        '                out[y, 1] = c',
        '            elif right is not None and c == right:',
        '                out[y, W - 2] = c',
        '    return out.tolist()',
        '',
    ]
    return '\n'.join(lines)
