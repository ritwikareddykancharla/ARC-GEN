def build_program(d4, palette):
    green = int(palette[3])
    red = int(palette[2])
    cyan = int(palette[8])
    black = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('GREEN = %d' % green)
    lines.append('RED = %d' % red)
    lines.append('CYAN = %d' % cyan)
    lines.append('BLACK = %d' % black)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    if g.ndim != 2:')
    lines.append('        return [list(r) for r in grid]')
    lines.append('    out = g.copy()')
    lines.append('    h, w = g.shape')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if g[y, x] != GREEN:')
    lines.append('                continue')
    lines.append('            partners = []')
    lines.append('            for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):')
    lines.append('                ny, nx = y + dy, x + dx')
    lines.append('                if 0 <= ny < h and 0 <= nx < w and g[ny, nx] == RED:')
    lines.append('                    partners.append((ny, nx))')
    lines.append('            if partners:')
    lines.append('                out[y, x] = CYAN')
    lines.append('                for ny, nx in partners:')
    lines.append('                    out[ny, nx] = BLACK')
    lines.append('    return out.astype(int).tolist()')
    lines.append('')
    return '\n'.join(lines)
