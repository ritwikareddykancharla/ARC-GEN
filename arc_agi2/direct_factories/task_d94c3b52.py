def build_program(d4, palette):
    bg = int(palette[0])
    fg = int(palette[1])
    tcol = int(palette[8])
    fcol = int(palette[7])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('FG = %d' % fg)
    lines.append('TEMPLATE = %d' % tcol)
    lines.append('FILL = %d' % fcol)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int).copy()')
    lines.append('    H, W = g.shape')
    lines.append('    R = (H - 1) // 4')
    lines.append('    C = (W - 1) // 4')
    lines.append('    def tile(r, c):')
    lines.append('        return g[1 + 4 * r:4 + 4 * r, 1 + 4 * c:4 + 4 * c]')
    lines.append('    tmpl = None')
    lines.append('    for r in range(R):')
    lines.append('        for c in range(C):')
    lines.append('            t = tile(r, c)')
    lines.append('            if tmpl is None and (t == TEMPLATE).any():')
    lines.append('                tmpl = (t != BG).copy()')
    lines.append('    if tmpl is None:')
    lines.append('        return g.tolist()')
    lines.append('    is_t = [[False] * C for _ in range(R)]')
    lines.append('    for r in range(R):')
    lines.append('        for c in range(C):')
    lines.append('            t = tile(r, c)')
    lines.append('            m = t != BG')
    lines.append('            if m.shape == tmpl.shape and np.array_equal(m, tmpl):')
    lines.append('                t[m] = TEMPLATE')
    lines.append('                is_t[r][c] = True')
    lines.append('    fill = set()')
    lines.append('    for r in range(R):')
    lines.append('        cols = [c for c in range(C) if is_t[r][c]]')
    lines.append('        if len(cols) >= 2:')
    lines.append('            for c in range(min(cols) + 1, max(cols)):')
    lines.append('                if not is_t[r][c]:')
    lines.append('                    fill.add((r, c))')
    lines.append('    for c in range(C):')
    lines.append('        rows = [r for r in range(R) if is_t[r][c]]')
    lines.append('        if len(rows) >= 2:')
    lines.append('            for r in range(min(rows) + 1, max(rows)):')
    lines.append('                if not is_t[r][c]:')
    lines.append('                    fill.add((r, c))')
    lines.append('    for (r, c) in fill:')
    lines.append('        t = tile(r, c)')
    lines.append('        t[t != BG] = FILL')
    lines.append('    return g.tolist()')
    return '\n'.join(lines) + '\n'
