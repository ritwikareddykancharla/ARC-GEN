def build_program(d4, palette):
    bg = int(palette[0])
    line = int(palette[3])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('LINE = %d' % line)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    mask = g != BG')
    lines.append('    ys, xs = np.nonzero(mask)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return out.tolist()')
    lines.append('    y0, y1 = int(ys.min()), int(ys.max())')
    lines.append('    x0, x1 = int(xs.min()), int(xs.max())')
    lines.append('    for y in range(y0, y1 + 1):')
    lines.append('        if not mask[y, :].any():')
    lines.append('            out[y, :] = LINE')
    lines.append('    for x in range(x0, x1 + 1):')
    lines.append('        if not mask[:, x].any():')
    lines.append('            out[:, x] = LINE')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
