def build_program(d4, palette):
    bg = int(palette[0])
    dot = int(palette[1])
    fill = int(palette[8])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DOT = %d' % dot)
    lines.append('FILL = %d' % fill)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    if g.ndim != 2:')
    lines.append('        return [list(r) for r in grid]')
    lines.append('    H, W = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    isdot = (g == DOT)')
    lines.append('    # bridge consecutive dots within every row of the visible grid')
    lines.append('    for y in range(H):')
    lines.append('        xs = [x for x in range(W) if isdot[y, x]]')
    lines.append('        for a, b in zip(xs, xs[1:]):')
    lines.append('            for x in range(a + 1, b):')
    lines.append('                if out[y, x] == BG:')
    lines.append('                    out[y, x] = FILL')
    lines.append('    # bridge consecutive dots within every column of the visible grid')
    lines.append('    for x in range(W):')
    lines.append('        ys = [y for y in range(H) if isdot[y, x]]')
    lines.append('        for a, b in zip(ys, ys[1:]):')
    lines.append('            for y in range(a + 1, b):')
    lines.append('                if out[y, x] == BG:')
    lines.append('                    out[y, x] = FILL')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
