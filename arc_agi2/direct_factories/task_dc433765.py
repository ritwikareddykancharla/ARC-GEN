def build_program(d4, palette):
    mover = int(palette[3])
    target = int(palette[4])
    bg = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('MOVER = %d' % mover)
    lines.append('TARGET = %d' % target)
    lines.append('BG = %d' % bg)
    lines.append('# D4 index %d: the sign-step-toward-target mechanism is equivariant under' % int(d4))
    lines.append('# every rotation/reflection, so it is applied directly in visible coordinates.')
    lines.append('')
    lines.append('def _sign(v):')
    lines.append('    return (v > 0) - (v < 0)')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int).copy()')
    lines.append('    H, W = g.shape')
    lines.append('    my_s, mx_s = np.where(g == MOVER)')
    lines.append('    ty_s, tx_s = np.where(g == TARGET)')
    lines.append('    if len(my_s) == 0 or len(ty_s) == 0:')
    lines.append('        return g.tolist()')
    lines.append('    my, mx = int(my_s[0]), int(mx_s[0])')
    lines.append('    ty, tx = int(ty_s[0]), int(tx_s[0])')
    lines.append('    dy = _sign(ty - my)')
    lines.append('    dx = _sign(tx - mx)')
    lines.append('    ny, nx = my + dy, mx + dx')
    lines.append('    if not (0 <= ny < H and 0 <= nx < W):')
    lines.append('        return g.tolist()')
    lines.append('    if (ny, nx) == (ty, tx):')
    lines.append('        return g.tolist()')
    lines.append('    g[my, mx] = BG')
    lines.append('    g[ny, nx] = MOVER')
    lines.append('    return g.tolist()')
    return '\n'.join(lines) + '\n'
