def build_program(d4, palette):
    horizontal = (d4 % 4) in (1, 3)
    bg = int(palette[0])
    div = int(palette[4])
    out = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('HORIZONTAL_DIVIDER = %r' % bool(horizontal))
    lines.append('BG = %d' % bg)
    lines.append('DIV = %d' % div)
    lines.append('OUT = %d' % out)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    if HORIZONTAL_DIVIDER:')
    lines.append('        cand = [y for y in range(H) if y == H - 1 - y and bool((g[y, :] == DIV).all())]')
    lines.append('        y = cand[0] if cand else H // 2')
    lines.append('        a = g[:y, :]')
    lines.append('        b = g[y + 1:, :]')
    lines.append('    else:')
    lines.append('        cand = [x for x in range(W) if x == W - 1 - x and bool((g[:, x] == DIV).all())]')
    lines.append('        x = cand[0] if cand else W // 2')
    lines.append('        a = g[:, :x]')
    lines.append('        b = g[:, x + 1:]')
    lines.append('    h = min(a.shape[0], b.shape[0])')
    lines.append('    w = min(a.shape[1], b.shape[1])')
    lines.append('    a = a[:h, :w]')
    lines.append('    b = b[:h, :w]')
    lines.append('    res = np.full((h, w), BG, dtype=int)')
    lines.append('    res[(a != BG) | (b != BG)] = OUT')
    lines.append('    return res.tolist()')
    return '\n'.join(lines) + '\n'
