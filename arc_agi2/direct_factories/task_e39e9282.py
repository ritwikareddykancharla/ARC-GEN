def build_program(d4, palette):
    bg = int(palette[8])
    c5 = int(palette[5])
    c6 = int(palette[6])
    mk = int(palette[9])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('# Specialised for D4 index %d. The rule uses all four orthogonal directions' % int(d4))
    lines.append('# symmetrically, so every rotation or reflection of the scene keeps the same')
    lines.append('# local mechanism in visible coordinates. Only the colour roles are specialised.')
    lines.append('BG = %d       # background (original 8)' % bg)
    lines.append('DISSOLVE = %d # squares that vanish (original 5)' % c5)
    lines.append('ABSORB = %d   # squares that stay and absorb markers (original 6)' % c6)
    lines.append('MARK = %d     # marker colour (original 9)' % mk)
    lines.append('DIRS = ((-1, 0), (1, 0), (0, -1), (0, 1))')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    moves = []')
    lines.append('    exts = []')
    lines.append('    for y in range(H):')
    lines.append('        for x in range(W):')
    lines.append('            if g[y, x] != MARK:')
    lines.append('                continue')
    lines.append('            for dy, dx in DIRS:')
    lines.append('                ny, nx = y + dy, x + dx')
    lines.append('                if 0 <= ny < H and 0 <= nx < W and g[ny, nx] in (DISSOLVE, ABSORB):')
    lines.append('                    if g[ny, nx] == ABSORB:')
    lines.append('                        ty, tx = y + 2 * dy, x + 2 * dx')
    lines.append('                        moves.append(((y, x), (ty, tx)))')
    lines.append('                    else:')
    lines.append('                        exts.append((ny, nx))')
    lines.append('                    break')
    lines.append('    # Markers touching an absorbing square move two cells inward,')
    lines.append('    # landing on that square\'s middle row or middle column.')
    lines.append('    for (sy, sx), _ in moves:')
    lines.append('        out[sy, sx] = BG')
    lines.append('    for _, (ty, tx) in moves:')
    lines.append('        if 0 <= ty < H and 0 <= tx < W:')
    lines.append('            out[ty, tx] = MARK')
    lines.append('    # Markers touching a dissolving square stay put and grow one cell inward.')
    lines.append('    for (ey, ex) in exts:')
    lines.append('        out[ey, ex] = MARK')
    lines.append('    # Every remaining cell of a dissolving square is cleared to background.')
    lines.append('    out[out == DISSOLVE] = BG')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
