def build_program(d4, palette):
    d4 = int(d4) % 8
    red = int(palette[2])
    grey = int(palette[5])
    bg = int(palette[0])
    # An odd number of quarter turns swaps the axes. The original top and bottom
    # rows, which own the corners, then become the visible left and right columns.
    rows_own_corners = (d4 % 4) in (0, 2)
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('RED = %d' % red)
    lines.append('GREY = %d' % grey)
    lines.append('BG = %d' % bg)
    lines.append('ROWS_OWN_CORNERS = %s' % ('True' if rows_own_corners else 'False'))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    ys, xs = np.nonzero(g != BG)')
    lines.append('    pts = [(int(y), int(x), int(g[y, x])) for y, x in zip(ys, xs)]')
    lines.append('    centres = [p for p in pts if p[2] == RED]')
    lines.append('    if not centres:')
    lines.append('        return g.tolist()')
    lines.append('    centre = centres[0]')
    lines.append('    others = [p for p in pts if p != centre]')
    lines.append('    if not others:')
    lines.append('        return g.tolist()')
    lines.append('    top = min(others, key=lambda p: p[0])')
    lines.append('    bot = max(others, key=lambda p: p[0])')
    lines.append('    left = min(others, key=lambda p: p[1])')
    lines.append('    right = max(others, key=lambda p: p[1])')
    lines.append('    y0, y1, x0, x1 = top[0], bot[0], left[1], right[1]')
    lines.append('    out = g.copy()')
    lines.append('    cy, cx = centre[0], centre[1]')
    lines.append('    # grey cross strictly inside the frame')
    lines.append('    out[cy, x0 + 1:x1] = GREY')
    lines.append('    out[y0 + 1:y1, cx] = GREY')
    lines.append('    if ROWS_OWN_CORNERS:')
    lines.append('        out[y0 + 1:y1, x0] = left[2]')
    lines.append('        out[y0 + 1:y1, x1] = right[2]')
    lines.append('        out[y0, x0:x1 + 1] = top[2]')
    lines.append('        out[y1, x0:x1 + 1] = bot[2]')
    lines.append('    else:')
    lines.append('        out[y0, x0 + 1:x1] = top[2]')
    lines.append('        out[y1, x0 + 1:x1] = bot[2]')
    lines.append('        out[y0:y1 + 1, x0] = left[2]')
    lines.append('        out[y0:y1 + 1, x1] = right[2]')
    lines.append('    out[cy, cx] = RED')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
