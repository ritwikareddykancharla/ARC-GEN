def build_program(d4, palette):
    DIV = int(palette[0])
    BG = int(palette[7])
    lines = [
        'import numpy as np',
        '',
        'DIV = %d' % DIV,
        'BG = %d' % BG,
        '',
        'def _spans(cuts, n):',
        '    edges = [-1] + sorted(cuts) + [n]',
        '    out = []',
        '    for i in range(len(edges) - 1):',
        '        a, b = edges[i], edges[i + 1]',
        '        if b - a > 1:',
        '            out.append((a + 1, b - 1))',
        '    return out',
        '',
        'def solve(demonstrations, grid):',
        '    g = np.array(grid, dtype=int)',
        '    H, W = g.shape',
        '    out = g.copy()',
        '    rows = [y for y in range(H) if np.all(g[y, :] == DIV)]',
        '    cols = [x for x in range(W) if np.all(g[:, x] == DIV)]',
        '    ys = _spans(rows, H)',
        '    xs = _spans(cols, W)',
        '    boxes = [(y0, x0, y1, x1) for (y0, y1) in ys for (x0, x1) in xs]',
        '    pat = None',
        '    pbox = None',
        '    for b in boxes:',
        '        y0, x0, y1, x1 = b',
        '        sub = g[y0:y1 + 1, x0:x1 + 1]',
        '        if np.any((sub != BG) & (sub != DIV)):',
        '            pat = sub.copy()',
        '            pbox = b',
        '            break',
        '    if pat is None:',
        '        counts = []',
        '        for b in boxes:',
        '            y0, x0, y1, x1 = b',
        '            counts.append(int(np.sum(g[y0:y1 + 1, x0:x1 + 1] == DIV)))',
        '        if counts:',
        '            m = max(counts)',
        '            if m > 1 and counts.count(m) == 1:',
        '                pbox = boxes[counts.index(m)]',
        '                y0, x0, y1, x1 = pbox',
        '                pat = g[y0:y1 + 1, x0:x1 + 1].copy()',
        '    if pat is None:',
        '        return out.tolist()',
        '    ph, pw = pat.shape',
        '    for b in boxes:',
        '        if b == pbox:',
        '            continue',
        '        y0, x0, y1, x1 = b',
        '        sub = g[y0:y1 + 1, x0:x1 + 1]',
        '        if sub.shape != (ph, pw):',
        '            continue',
        '        if np.any(sub == DIV):',
        '            out[y0:y1 + 1, x0:x1 + 1] = pat',
        '    return out.tolist()',
        '',
    ]
    return '\n'.join(lines)
