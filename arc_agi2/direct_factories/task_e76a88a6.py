def build_program(d4, palette):
    bg = int(palette[0])
    grey = int(palette[5])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter, deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('GREY = %d' % grey)
    lines.append('')
    lines.append('def _components(mask):')
    lines.append('    h, w = mask.shape')
    lines.append('    seen = np.zeros_like(mask, bool)')
    lines.append('    out = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if mask[y, x] and not seen[y, x]:')
    lines.append('                q = deque([(y, x)])')
    lines.append('                seen[y, x] = True')
    lines.append('                cells = []')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('                out.append(cells)')
    lines.append('    return out')
    lines.append('')
    lines.append('def _bbox(cells):')
    lines.append('    ys = [c[0] for c in cells]')
    lines.append('    xs = [c[1] for c in cells]')
    lines.append('    return min(ys), min(xs), max(ys), max(xs)')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    out = g.copy()')
    lines.append('    comps = _components(g == GREY)')
    lines.append('    pm = (g != BG) & (g != GREY)')
    lines.append('    if not comps or not pm.any():')
    lines.append('        return out.tolist()')
    lines.append('    ys, xs = np.nonzero(pm)')
    lines.append('    ty0, tx0, ty1, tx1 = int(ys.min()), int(xs.min()), int(ys.max()), int(xs.max())')
    lines.append('    ph, pw = ty1 - ty0 + 1, tx1 - tx0 + 1')
    lines.append('    boxes = [_bbox(c) for c in comps]')
    lines.append('    sizes = Counter((b[2] - b[0] + 1, b[3] - b[1] + 1) for b in boxes)')
    lines.append('    bh, bw = sizes.most_common(1)[0][0]')
    lines.append('    th, tw = max(ph, bh), max(pw, bw)')
    lines.append('    th, tw = min(th, h), min(tw, w)')
    lines.append('    y0 = max(0, min(ty0, h - th))')
    lines.append('    x0 = max(0, min(tx0, w - tw))')
    lines.append('    tpl = g[y0:y0 + th, x0:x0 + tw].copy()')
    lines.append('    for (by0, bx0, by1, bx1) in boxes:')
    lines.append('        for dy in range(min(th, by1 - by0 + 1)):')
    lines.append('            for dx in range(min(tw, bx1 - bx0 + 1)):')
    lines.append('                yy, xx = by0 + dy, bx0 + dx')
    lines.append('                if 0 <= yy < h and 0 <= xx < w:')
    lines.append('                    out[yy, xx] = tpl[dy, dx]')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
