def build_program(d4, palette):
    bg = int(palette[0])
    wall = int(palette[5])
    horizontal_out = (int(d4) % 4) in (1, 3)
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('WALL = %d' % wall)
    lines.append('HORIZONTAL_OUT = %s' % ('True' if horizontal_out else 'False'))
    lines.append('')
    lines.append('def _count_components(mask):')
    lines.append('    h, w = mask.shape')
    lines.append('    seen = np.zeros((h, w), dtype=bool)')
    lines.append('    count = 0')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if mask[y, x] and not seen[y, x]:')
    lines.append('                count += 1')
    lines.append('                seen[y, x] = True')
    lines.append('                q = deque([(y, x)])')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('    return count')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.asarray(grid, dtype=int)')
    lines.append('    mask = (g == WALL)')
    lines.append('    n = _count_components(mask)')
    lines.append('    length = n + 1')
    lines.append('    if HORIZONTAL_OUT:')
    lines.append('        return [[BG] * length]')
    lines.append('    return [[BG] for _ in range(length)]')
    return '\n'.join(lines) + '\n'
