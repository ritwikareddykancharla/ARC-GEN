def build_program(d4, palette):
    bg = int(palette[0])
    div = int(palette[4])
    order = [int(palette[2]), int(palette[9]), int(palette[7]), int(palette[8])]
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('DIV = %d' % div)
    lines.append('ORDER = %r  # lowest to highest priority' % (order,))
    lines.append('D4 = %d  # mechanism is D4-equivariant; kept for reference only' % int(d4))
    lines.append('')
    lines.append('def _divider(g, axis):')
    lines.append('    H, W = g.shape')
    lines.append('    if axis == 0:')
    lines.append('        idx = [y for y in range(H) if (g[y, :] == DIV).all()]')
    lines.append('        n = H')
    lines.append('    else:')
    lines.append('        idx = [x for x in range(W) if (g[:, x] == DIV).all()]')
    lines.append('        n = W')
    lines.append('    if not idx:')
    lines.append('        return n // 2')
    lines.append('    centre = (n - 1) / 2.0')
    lines.append('    idx.sort(key=lambda i: (abs(i - centre), i))')
    lines.append('    return idx[0]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    dr = _divider(g, 0)')
    lines.append('    dc = _divider(g, 1)')
    lines.append('    panels = [g[:dr, :dc], g[:dr, dc + 1:], g[dr + 1:, :dc], g[dr + 1:, dc + 1:]]')
    lines.append('    panels = [p for p in panels if p.size > 0]')
    lines.append('    h = min(p.shape[0] for p in panels)')
    lines.append('    w = min(p.shape[1] for p in panels)')
    lines.append('    panels = [p[:h, :w] for p in panels]')
    lines.append('    out = np.full((h, w), BG, dtype=int)')
    lines.append('    others = set()')
    lines.append('    for p in panels:')
    lines.append('        for c in np.unique(p).tolist():')
    lines.append('            if c != BG and c != DIV and c not in ORDER:')
    lines.append('                others.add(int(c))')
    lines.append('    for c in sorted(others):')
    lines.append('        for p in panels:')
    lines.append('            out[p == c] = c')
    lines.append('    for c in ORDER:')
    lines.append('        for p in panels:')
    lines.append('            out[p == c] = c')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
