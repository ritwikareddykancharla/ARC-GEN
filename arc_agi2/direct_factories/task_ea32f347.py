def build_program(d4, palette):
    pal = [int(palette[c]) for c in range(10)]
    grey = pal[5]
    bg = pal[0]
    rank_colours = [pal[1], pal[4], pal[2]]
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import deque')
    lines.append('')
    lines.append('# Specialised for D4 index %d. Ranking by bar length is invariant under' % int(d4))
    lines.append('# rotation and reflection, so no axis is chosen; colours are palette constants.')
    lines.append('GREY = %d' % grey)
    lines.append('BG = %d' % bg)
    lines.append('RANK_COLOURS = [%d, %d, %d]  # longest, middle, shortest' % tuple(rank_colours))
    lines.append('')
    lines.append('def _components(mask):')
    lines.append('    h, w = mask.shape')
    lines.append('    seen = np.zeros_like(mask, dtype=bool)')
    lines.append('    comps = []')
    lines.append('    for y in range(h):')
    lines.append('        for x in range(w):')
    lines.append('            if mask[y, x] and not seen[y, x]:')
    lines.append('                seen[y, x] = True')
    lines.append('                q = deque([(y, x)])')
    lines.append('                cells = []')
    lines.append('                while q:')
    lines.append('                    cy, cx = q.popleft()')
    lines.append('                    cells.append((cy, cx))')
    lines.append('                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):')
    lines.append('                        ny, nx = cy + dy, cx + dx')
    lines.append('                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:')
    lines.append('                            seen[ny, nx] = True')
    lines.append('                            q.append((ny, nx))')
    lines.append('                comps.append(sorted(cells))')
    lines.append('    return comps')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    comps = _components(g == GREY)')
    lines.append('    # Longest bar first; generator guarantees distinct lengths.')
    lines.append('    comps.sort(key=lambda c: -len(c))')
    lines.append('    for i, cells in enumerate(comps):')
    lines.append('        col = RANK_COLOURS[min(i, len(RANK_COLOURS) - 1)]')
    lines.append('        for y, x in cells:')
    lines.append('            out[y, x] = col')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
