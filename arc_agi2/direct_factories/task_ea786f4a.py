def build_program(d4, palette):
    seed_colour = int(palette[0])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('')
    lines.append('SEED_COLOUR = %d' % seed_colour)
    lines.append('DIRS = [(-1, -1), (-1, 1), (1, -1), (1, 1)]')
    lines.append('')
    lines.append('def _background(g):')
    lines.append('    cnt = Counter(g.ravel().tolist())')
    lines.append('    best = max(cnt.values())')
    lines.append('    cands = sorted(c for c, n in cnt.items() if n == best and c != SEED_COLOUR)')
    lines.append('    if cands:')
    lines.append('        return int(cands[0])')
    lines.append('    return int(cnt.most_common(1)[0][0])')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    out = g.copy()')
    lines.append('    h, w = g.shape')
    lines.append('    bg = _background(g)')
    lines.append('    seeds = [(y, x) for y in range(h) for x in range(w) if g[y, x] == SEED_COLOUR and g[y, x] != bg]')
    lines.append('    if not seeds:')
    lines.append('        seeds = [(y, x) for y in range(h) for x in range(w) if g[y, x] != bg]')
    lines.append('    for sy, sx in seeds:')
    lines.append('        c = int(g[sy, sx])')
    lines.append('        for dy, dx in DIRS:')
    lines.append('            y, x = sy + dy, sx + dx')
    lines.append('            while 0 <= y < h and 0 <= x < w:')
    lines.append('                out[y, x] = c')
    lines.append('                y += dy')
    lines.append('                x += dx')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
