def build_program(d4, palette):
    pal = [int(palette[i]) for i in range(10)]
    bg = pal[7]
    fill = pal[0]
    over = pal[9]
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('FILL = %d' % fill)
    lines.append('OVER = %d' % over)
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.asarray(grid, dtype=int)')
    lines.append('    h, w = g.shape')
    lines.append('    ys, xs = np.nonzero(g != BG)')
    lines.append('    if len(ys) == 0:')
    lines.append('        y0, x0 = 0, 0')
    lines.append('        has = False')
    lines.append('    else:')
    lines.append('        y0, x0 = int(ys.min()), int(xs.min())')
    lines.append('        has = True')
    lines.append('    def filled(r, c):')
    lines.append('        if not has:')
    lines.append('            return False')
    lines.append('        yy, xx = y0 + r, x0 + c')
    lines.append('        if yy < 0 or yy >= h or xx < 0 or xx >= w:')
    lines.append('            return False')
    lines.append('        return bool(g[yy, xx] != BG)')
    lines.append('    def col(v):')
    lines.append('        return FILL if v else BG')
    lines.append('    # keys: (row index is a line, column index is a line)')
    lines.append('    kind = {')
    lines.append('        (True, True): col(filled(1, 1)),')
    lines.append('        (True, False): col(filled(1, 0)),')
    lines.append('        (False, True): col(filled(0, 1)),')
    lines.append('        (False, False): col(filled(0, 0)),')
    lines.append('    }')
    lines.append('    out = []')
    lines.append('    for y in range(16):')
    lines.append('        row = []')
    lines.append('        for x in range(16):')
    lines.append('            v = kind[(y % 3 == 0, x % 3 == 0)]')
    lines.append('            if 5 <= y <= 10 and 5 <= x <= 10 and v == FILL:')
    lines.append('                v = OVER')
    lines.append('            row.append(int(v))')
    lines.append('        out.append(row)')
    lines.append('    return out')
    lines.append('')
    return '\n'.join(lines)
