def build_program(d4, palette):
    bg = int(palette[0])
    shape_c = int(palette[8])
    anchor_c = int(palette[3])
    target_c = int(palette[2])
    lines = []
    lines.append('import numpy as np')
    lines.append('')
    lines.append('BG = %d' % bg)
    lines.append('SHAPE = %d' % shape_c)
    lines.append('ANCHOR = %d' % anchor_c)
    lines.append('TARGET = %d' % target_c)
    lines.append('D4 = %d' % int(d4))
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    out = np.full((H, W), BG, dtype=int)')
    lines.append('    anchors = np.argwhere(g == ANCHOR)')
    lines.append('    if len(anchors) == 0:')
    lines.append('        return out.tolist()')
    lines.append('    ay, ax = int(anchors[0][0]), int(anchors[0][1])')
    lines.append('    shape = [(int(r), int(c)) for r, c in np.argwhere(g == SHAPE)]')
    lines.append('    targets = [(int(r), int(c)) for r, c in np.argwhere(g == TARGET)]')
    lines.append('    for ty, tx in targets:')
    lines.append('        dy = ty - ay')
    lines.append('        dx = tx - ax')
    lines.append('        for y, x in shape:')
    lines.append('            ny = y + dy')
    lines.append('            nx = x + dx')
    lines.append('            if 0 <= ny < H and 0 <= nx < W:')
    lines.append('                out[ny, nx] = SHAPE')
    lines.append('    return out.tolist()')
    return '\n'.join(lines) + '\n'
