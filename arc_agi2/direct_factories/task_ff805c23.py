def build_program(d4, palette):
    patch = int(palette[1])
    lines = []
    lines.append('import numpy as np')
    lines.append('from collections import Counter')
    lines.append('')
    lines.append('PATCH = %d' % patch)
    lines.append('')
    lines.append('def _partners(y, x, H, W):')
    lines.append('    # full dihedral orbit of a cell in a square canvas (orbit set is invariant under every D4 view)')
    lines.append('    return [(y, W - 1 - x), (H - 1 - y, x), (H - 1 - y, W - 1 - x),')
    lines.append('            (x, y), (x, H - 1 - y), (W - 1 - x, y), (W - 1 - x, H - 1 - y)]')
    lines.append('')
    lines.append('def solve(demonstrations, grid):')
    lines.append('    g = np.array(grid, dtype=int)')
    lines.append('    H, W = g.shape')
    lines.append('    ys, xs = np.where(g == PATCH)')
    lines.append('    if len(ys) == 0:')
    lines.append('        return g.tolist()')
    lines.append('    y0, y1, x0, x1 = int(ys.min()), int(ys.max()), int(xs.min()), int(xs.max())')
    lines.append('    rep = g.copy()')
    lines.append('    for y, x in zip(ys.tolist(), xs.tolist()):')
    lines.append('        vals = []')
    lines.append('        for py, px in _partners(y, x, H, W):')
    lines.append('            if 0 <= py < H and 0 <= px < W and g[py, px] != PATCH:')
    lines.append('                vals.append(int(g[py, px]))')
    lines.append('        if vals:')
    lines.append('            # all clean partners share the orbit colour; majority vote only guards against noise')
    lines.append('            rep[y, x] = Counter(vals).most_common(1)[0][0]')
    lines.append('    out = rep[y0:y1 + 1, x0:x1 + 1]')
    lines.append('    return out.astype(int).tolist()')
    return '\n'.join(lines) + '\n'
