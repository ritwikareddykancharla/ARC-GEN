"""Second-reviewer tests for b7955b3c (independent of the original author's tests).

1. Soundness of rejection: every reading enumerated by the emitted solver is
   re-expressed as explicit native parameters and re-generated by the
   *unchanged* native constructor; it must reproduce the visible input exactly
   and render the reading as output.  Hence whenever the solver raises, two
   genuinely native scenes share the input but differ in output (intrinsic
   ambiguity, not a solver gap).
2. Completeness: the true scene is always among the readings, so a unique
   reading is the true output (no wrong answers possible).
3. Dense adversarial scenes (many large overlapping boxes, many pluses, small
   grids, explicit params) – solver and independent gate agree, every answer
   is correct, and every raise is certified by (1).
4. The witness remains ambiguous even under the random-branch count prior
   (num_boxes = f(W*H), num_plusses in [nb//2, nb]).
5. The gate is callable with queries=[{'input': grid}] and never sees labels.
"""
import json
import random
import unittest

from arc_agi2.direct_factories.task_b7955b3c import build_program
from arc_agi2.occluded_boxes_b7955b3c_evidence import (
    IntrinsicAmbiguity, readings, require_occluded_boxes_evidence)
from arc_agi2.program_targets import audit_target
from tasks import task_b7955b3c as native

ID = list(range(10))


def ns_for(pal=ID):
    src = build_program(0, pal)
    audit_target('b7955b3c', src)
    ns = {}
    exec(src, ns)
    return ns


NS = ns_for()


def solver_readings(g):
    """bg -> output for every reading the emitted program accepts."""
    cells = NS['_cells'](g)
    res = {}
    for bg in NS['COLOURS']:
        boxes = [c for c in sorted(cells) if c != bg]
        out = NS['_reading'](g, cells, boxes, bg)
        if out is not None:
            res[bg] = out
    return res


def plus_centres(g):
    H, W = len(g), len(g[0])
    cs = []
    for r in range(1, H - 1):
        for k in range(1, W - 1):
            if all(g[r + dr][k + dc] == 8 for dr, dc in
                   [(0, 0), (0, 1), (0, -1), (1, 0), (-1, 0)]):
                cs.append((r, k))
    return cs


def reading_to_params(g, bg, out):
    """Explicit native params whose draw() should reproduce (g, out)."""
    H, W = len(g), len(g[0])
    cells = NS['_cells'](g)
    boxes = [c for c in sorted(cells) if c != bg]
    rect = {}
    for c in boxes:
        rs = [p[0] for p in cells[c]]
        ks = [p[1] for p in cells[c]]
        rect[c] = (min(rs), min(ks), max(rs), max(ks))
    # Stack order: a below b iff they overlap and b visible in the overlap.
    def over(a, b):
        ra, rb = rect[a], rect[b]
        t, l = max(ra[0], rb[0]), max(ra[1], rb[1])
        u, d = min(ra[2], rb[2]), min(ra[3], rb[3])
        if t > u or l > d:
            return False
        return any(t <= r <= u and l <= k <= d for r, k in cells[b])
    order, left = [], list(boxes)
    while left:
        c = next(c for c in left if not any(over(c, o) for o in left if o != c))
        order.insert(0, c)
        left.remove(c)
    cs = plus_centres(g)
    return dict(width=W, height=H, bgcolor=bg,
                wides=[rect[c][3] - rect[c][1] + 1 for c in order],
                talls=[rect[c][2] - rect[c][0] + 1 for c in order],
                brows=[rect[c][0] for c in order], bcols=[rect[c][1] for c in order],
                bcolors=order, prows=[r for r, _ in cs], pcols=[k for _, k in cs])


def certify(testcase, pair):
    g = pair['input']
    res = solver_readings(g)
    testcase.assertIn(pair['output'], list(res.values()))  # completeness
    for bg, out in res.items():
        p = reading_to_params(g, bg, out)
        regen = native.generate(**p)
        testcase.assertEqual(regen['input'], g, (bg, p))
        testcase.assertEqual(regen['output'], out, (bg, p))
    return res


def dense_params(rng):
    # Edge-anchored large boxes so the background is often hidden entirely or
    # survives only under pluses: this is where hard/ambiguous scenes live.
    W, H = rng.randint(5, 12), rng.randint(5, 12)
    n = rng.randint(2, 6)
    cols = rng.sample([0, 1, 2, 3, 4, 5, 6, 7, 9], n + 1)
    bg = cols.pop()
    def ext(L):
        return rng.choice([rng.randint(1, L - 2), rng.randint(max(1, L // 2), L - 2), L - 2])
    wides = [ext(W) for _ in range(n)]
    talls = [ext(H) for _ in range(n)]
    def pos(L, e):
        return rng.choice([0, L - e, rng.randint(0, L - e)])
    k = rng.randint(1, 4)
    return dict(width=W, height=H, bgcolor=bg, wides=wides, talls=talls,
                brows=[pos(H, t) for t in talls], bcols=[pos(W, w) for w in wides],
                bcolors=cols, prows=[rng.randint(1, H - 2) for _ in range(k)],
                pcols=[rng.randint(1, W - 2) for _ in range(k)])


WITNESS = dict(width=16, height=16, wides=[8, 8, 11, 4], talls=[14, 14, 2, 2],
               brows=[0, 0, 14, 14], bcols=[0, 8, 5, 0], bcolors=[0, 1, 2, 3],
               prows=[14, 5], pcols=[4, 11])


class ReviewV6(unittest.TestCase):
    def test_dense_adversarial_soundness(self):
        rng = random.Random(7955)
        demos = native.validate()['train']
        stats = dict(drawn=0, unique=0, hard=0, ambiguous=0)
        while stats['drawn'] < 1500:
            p = dense_params(rng)
            pair = native.generate(**p)
            if pair['input'] is None:
                continue
            stats['drawn'] += 1
            res = certify(self, pair)
            gate_res = readings(pair['input'], 8)
            self.assertEqual(sorted(res), sorted(gate_res))
            outs = {json.dumps(o) for o in res.values()}
            try:
                got = NS['solve'](demos, pair['input'])
            except ValueError:
                got = None
            gate_ok = True
            try:
                require_occluded_boxes_evidence(demos, [{'input': pair['input']}], ID)
            except IntrinsicAmbiguity:
                gate_ok = False
            if len(outs) == 1:
                self.assertEqual(got, pair['output'])
                self.assertTrue(gate_ok)
                stats['hard' if len(res) > 1 else 'unique'] += 1
            else:
                self.assertIsNone(got)
                self.assertFalse(gate_ok)
                stats['ambiguous'] += 1
        # Dense scenes must actually exercise hard and ambiguous cases.
        self.assertGreater(stats['hard'], 0, stats)
        self.assertGreater(stats['ambiguous'], 0, stats)
        print('dense', stats)

    def test_native_random_branch_soundness(self):
        for i in range(300):
            random.seed(79550000 + i)
            pair = native.generate()
            res = certify(self, pair)
            outs = {json.dumps(o) for o in res.values()}
            if len(outs) == 1:
                self.assertEqual(NS['solve']([], pair['input']), pair['output'])

    def test_witness_ambiguous_under_random_branch_prior(self):
        W, H = WITNESS['width'], WITNESS['height']
        nb = 2
        for a, k in ((125, 3), (250, 4), (375, 5), (500, 6)):
            if W * H >= a:
                nb = k
        a = native.generate(bgcolor=4, **WITNESS)
        b = native.generate(bgcolor=5, **WITNESS)
        self.assertEqual(a['input'], b['input'])
        self.assertNotEqual(a['output'], b['output'])
        self.assertEqual(len(WITNESS['bcolors']), nb)
        self.assertTrue(nb // 2 <= len(WITNESS['prows']) <= nb)
        res = certify(self, a)
        self.assertIn(4, res)
        self.assertIn(5, res)

    def test_gate_query_only_signature(self):
        data = native.validate()
        for q in data['test']:
            out = require_occluded_boxes_evidence(data['train'], queries=[{'input': q['input']}], palette=ID)
            self.assertEqual(out, {'plus': 8})

    def test_program_has_no_d4_dependence(self):
        pal = [3, 9, 0, 7, 2, 8, 1, 6, 4, 5]
        self.assertEqual(len({build_program(d, pal) for d in range(8)}), 1)
        self.assertIn('PLUS = 4', build_program(0, pal))


if __name__ == '__main__':
    unittest.main()
